-- 4. Nueva Tabla de Calificaciones Definitivas de Periodo por Área Curricular (UC-17, RN-CAL-03, UC-PROV-07 A2)
CREATE TABLE IF NOT EXISTS calificaciones_area_periodo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id BIGINT NOT NULL,
    area_id BIGINT NOT NULL,
    periodo_academico_id BIGINT NOT NULL,
    nota_definitiva NUMERIC(4,2) NOT NULL,
    desempeno VARCHAR(20) NOT NULL,
    aprobada BOOLEAN NOT NULL,
    origen VARCHAR(35) NOT NULL DEFAULT 'CALCULADA',
    fecha_calculo TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_calif_area_mat_area_per UNIQUE (matricula_id, area_id, periodo_academico_id),
    CONSTRAINT fk_calif_area_matricula FOREIGN KEY (matricula_id) REFERENCES matriculas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_calif_area_area FOREIGN KEY (area_id) REFERENCES areas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_calif_area_periodo FOREIGN KEY (periodo_academico_id) REFERENCES periodos_academicos (id) ON DELETE RESTRICT,
    CONSTRAINT chk_calif_area_desempeno CHECK (desempeno IN ('SUPERIOR', 'ALTO', 'BASICO', 'BAJO')),
    CONSTRAINT chk_calif_area_origen CHECK (origen IN ('CALCULADA', 'CONVALIDADA_TRASLADO', 'CONVALIDADA_PROMOCION_ANTICIPADA'))
);

CREATE INDEX IF NOT EXISTS idx_calif_area_matricula ON calificaciones_area_periodo (matricula_id);
CREATE INDEX IF NOT EXISTS idx_calif_area_area ON calificaciones_area_periodo (area_id);
CREATE INDEX IF NOT EXISTS idx_calif_area_periodo ON calificaciones_area_periodo (periodo_academico_id);

-- 5. Nueva Tabla de Actas de Nivelación y Apoyo Pedagógico (UC-18, RN-CAL-07, RN-CFG-04)
CREATE TABLE IF NOT EXISTS actas_nivelacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_acta VARCHAR(50) NOT NULL,
    calificacion_periodo_id BIGINT NOT NULL,
    matricula_id BIGINT NOT NULL,
    asignatura_id BIGINT NOT NULL,
    periodo_academico_id BIGINT NOT NULL,
    docente_id BIGINT,
    fecha_sustentacion DATE NOT NULL,
    asistencia BOOLEAN NOT NULL DEFAULT TRUE,
    nota_original NUMERIC(4,2) NOT NULL,
    nota_obtenida NUMERIC(4,2),
    formula_aplicada VARCHAR(30) NOT NULL,
    nota_final_resultante NUMERIC(4,2) NOT NULL,
    desempeno_resultante VARCHAR(20) NOT NULL,
    estrategia_pedagogica TEXT,
    evidencias_soporte VARCHAR(255),
    observaciones VARCHAR(255),
    usuario_registro_id BIGINT,
    fecha_registro TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_actas_nivelacion_numero UNIQUE (numero_acta),
    CONSTRAINT fk_acta_niv_calif_periodo FOREIGN KEY (calificacion_periodo_id) REFERENCES calificaciones_periodo (id) ON DELETE RESTRICT,
    CONSTRAINT fk_acta_niv_matricula FOREIGN KEY (matricula_id) REFERENCES matriculas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_acta_niv_asignatura FOREIGN KEY (asignatura_id) REFERENCES asignaturas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_acta_niv_periodo FOREIGN KEY (periodo_academico_id) REFERENCES periodos_academicos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_acta_niv_docente FOREIGN KEY (docente_id) REFERENCES profesores (id) ON DELETE SET NULL,
    CONSTRAINT fk_acta_niv_usuario FOREIGN KEY (usuario_registro_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_acta_niv_formula CHECK (formula_aplicada IN ('REEMPLAZO_TOTAL', 'TOPE_BASICO', 'PROMEDIO_PONDERADO')),
    CONSTRAINT chk_acta_niv_desempeno CHECK (desempeno_resultante IN ('SUPERIOR', 'ALTO', 'BASICO', 'BAJO'))
);

CREATE INDEX IF NOT EXISTS idx_acta_niv_matricula ON actas_nivelacion (matricula_id);
CREATE INDEX IF NOT EXISTS idx_acta_niv_calif_periodo ON actas_nivelacion (calificacion_periodo_id);
CREATE INDEX IF NOT EXISTS idx_acta_niv_periodo ON actas_nivelacion (periodo_academico_id);

-- 6. Nueva Tabla de Reclamaciones Académicas sobre Calificaciones (UC-PROV-15, RN-CAL-09, Ley 1581)
CREATE TABLE IF NOT EXISTS reclamaciones_calificacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_radicado VARCHAR(50) NOT NULL,
    tipo_calificacion VARCHAR(30) NOT NULL,
    referencia_id BIGINT NOT NULL,
    matricula_id BIGINT NOT NULL,
    solicitante_usuario_id BIGINT NOT NULL,
    rol_solicitante VARCHAR(20) NOT NULL,
    motivo_reclamacion TEXT NOT NULL,
    soporte_url VARCHAR(255),
    estado VARCHAR(35) NOT NULL DEFAULT 'RADICADA_PRIMERA_INSTANCIA',
    fecha_radicacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_limite_respuesta DATE NOT NULL,
    decision_primera_instancia VARCHAR(30),
    motivo_primera_instancia TEXT,
    fecha_decision_primera_instancia TIMESTAMP(6) WITHOUT TIME ZONE,
    docente_resolutor_id BIGINT,
    decision_segunda_instancia VARCHAR(30),
    motivo_segunda_instancia TEXT,
    fecha_decision_segunda_instancia TIMESTAMP(6) WITHOUT TIME ZONE,
    coordinador_resolutor_id BIGINT,
    nueva_nota_aprobada NUMERIC(4,2),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_reclamacion_radicado UNIQUE (numero_radicado),
    CONSTRAINT fk_reclamacion_matricula FOREIGN KEY (matricula_id) REFERENCES matriculas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_reclamacion_solicitante FOREIGN KEY (solicitante_usuario_id) REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT fk_reclamacion_docente FOREIGN KEY (docente_resolutor_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT fk_reclamacion_coordinador FOREIGN KEY (coordinador_resolutor_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_reclamacion_tipo CHECK (tipo_calificacion IN ('ACTIVIDAD', 'PERIODO', 'NIVELACION')),
    CONSTRAINT chk_reclamacion_rol CHECK (rol_solicitante IN ('ESTUDIANTE', 'ACUDIENTE')),
    CONSTRAINT chk_reclamacion_estado CHECK (estado IN (
        'RADICADA_PRIMERA_INSTANCIA',
        'RESUELTA_FAVORABLE_DOCENTE',
        'RECHAZADA_DOCENTE',
        'ESCALADA_SEGUNDA_INSTANCIA',
        'RESUELTA_FAVORABLE_COORDINACION',
        'RECHAZADA_COORDINACION'
    )),
    CONSTRAINT chk_reclamacion_dec_1 CHECK (decision_primera_instancia IS NULL OR decision_primera_instancia IN ('APROBAR_RECTIFICACION', 'RECHAZAR_MANTENER_NOTA')),
    CONSTRAINT chk_reclamacion_dec_2 CHECK (decision_segunda_instancia IS NULL OR decision_segunda_instancia IN ('APROBAR_RECTIFICACION', 'RECHAZAR_MANTENER_NOTA'))
);

CREATE INDEX IF NOT EXISTS idx_reclamacion_matricula ON reclamaciones_calificacion (matricula_id);
CREATE INDEX IF NOT EXISTS idx_reclamacion_ref ON reclamaciones_calificacion (tipo_calificacion, referencia_id);
CREATE INDEX IF NOT EXISTS idx_reclamacion_estado ON reclamaciones_calificacion (estado);
CREATE INDEX IF NOT EXISTS idx_reclamacion_fecha_limite ON reclamaciones_calificacion (fecha_limite_respuesta);

-- 7. Nuevas Tablas de Convalidación Curricular de Periodos Previos (UC-PROV-16, RN-CAL-10)
CREATE TABLE IF NOT EXISTS convalidaciones_calificacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_acta VARCHAR(50) NOT NULL,
    matricula_id BIGINT NOT NULL,
    periodo_academico_id BIGINT NOT NULL,
    tipo_origen VARCHAR(35) NOT NULL,
    institucion_origen VARCHAR(150),
    acta_soporte_url VARCHAR(255),
    observaciones TEXT,
    coordinador_id BIGINT,
    fecha_convalidacion DATE NOT NULL DEFAULT CURRENT_DATE,
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_convalidacion_acta UNIQUE (numero_acta),
    CONSTRAINT fk_convalidacion_matricula FOREIGN KEY (matricula_id) REFERENCES matriculas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_convalidacion_periodo FOREIGN KEY (periodo_academico_id) REFERENCES periodos_academicos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_convalidacion_coordinador FOREIGN KEY (coordinador_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_convalidacion_origen CHECK (tipo_origen IN ('TRASLADO_ENTRANTE', 'PROMOCION_ANTICIPADA'))
);

CREATE INDEX IF NOT EXISTS idx_convalidacion_matricula ON convalidaciones_calificacion (matricula_id);
CREATE INDEX IF NOT EXISTS idx_convalidacion_periodo ON convalidaciones_calificacion (periodo_academico_id);

CREATE TABLE IF NOT EXISTS convalidaciones_calificacion_detalle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    convalidacion_id BIGINT NOT NULL,
    asignatura_id BIGINT NOT NULL,
    nota_convalidada NUMERIC(4,2) NOT NULL,
    desempeno VARCHAR(20) NOT NULL,
    observaciones VARCHAR(255),
    CONSTRAINT uk_conv_det_conv_asig UNIQUE (convalidacion_id, asignatura_id),
    CONSTRAINT fk_conv_det_convalidacion FOREIGN KEY (convalidacion_id) REFERENCES convalidaciones_calificacion (id) ON DELETE CASCADE,
    CONSTRAINT fk_conv_det_asignatura FOREIGN KEY (asignatura_id) REFERENCES asignaturas (id) ON DELETE RESTRICT,
    CONSTRAINT chk_conv_det_desempeno CHECK (desempeno IN ('SUPERIOR', 'ALTO', 'BASICO', 'BAJO'))
);

CREATE INDEX IF NOT EXISTS idx_conv_det_convalidacion ON convalidaciones_calificacion_detalle (convalidacion_id);
