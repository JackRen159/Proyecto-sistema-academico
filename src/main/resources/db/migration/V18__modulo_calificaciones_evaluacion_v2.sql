-- 1. Ampliación de Actividades Evaluativas (UC-16, RN-CAL-01, RN-CAL-02, RN-CAL-08)
ALTER TABLE actividades_evaluativas
    ADD COLUMN IF NOT EXISTS categoria_evaluativa VARCHAR(30) NOT NULL DEFAULT 'COGNITIVA',
    ADD COLUMN IF NOT EXISTS tipo_componente VARCHAR(30) NOT NULL DEFAULT 'TALLER',
    ADD COLUMN IF NOT EXISTS modalidad VARCHAR(30) NOT NULL DEFAULT 'HETEROEVALUACION',
    ADD COLUMN IF NOT EXISTS estado VARCHAR(20) NOT NULL DEFAULT 'PUBLICADA',
    ADD COLUMN IF NOT EXISTS siee_version_id BIGINT,
    ADD COLUMN IF NOT EXISTS es_adaptacion_piar BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS criterios_adaptados_piar TEXT,
    ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_actividades_siee_version') THEN
        ALTER TABLE actividades_evaluativas
            ADD CONSTRAINT fk_actividades_siee_version
            FOREIGN KEY (siee_version_id) REFERENCES configuracion_siee_versiones (id) ON DELETE SET NULL;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_actividades_categoria') THEN
        ALTER TABLE actividades_evaluativas
            ADD CONSTRAINT chk_actividades_categoria
            CHECK (categoria_evaluativa IN ('COGNITIVA', 'PROCEDIMENTAL', 'ACTITUDINAL', 'AUTOEVALUACION', 'COEVALUACION', 'PERIODO'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_actividades_componente') THEN
        ALTER TABLE actividades_evaluativas
            ADD CONSTRAINT chk_actividades_componente
            CHECK (tipo_componente IN ('QUIZ', 'TALLER', 'TAREA', 'PROYECTO', 'SUSTENTACION', 'EXAMEN', 'OTRO'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_actividades_modalidad') THEN
        ALTER TABLE actividades_evaluativas
            ADD CONSTRAINT chk_actividades_modalidad
            CHECK (modalidad IN ('HETEROEVALUACION', 'AUTOEVALUACION', 'COEVALUACION'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_actividades_estado') THEN
        ALTER TABLE actividades_evaluativas
            ADD CONSTRAINT chk_actividades_estado
            CHECK (estado IN ('BORRADOR', 'PUBLICADA'));
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_actividades_estado ON actividades_evaluativas (estado);
CREATE INDEX IF NOT EXISTS idx_actividades_siee_version ON actividades_evaluativas (siee_version_id);

-- 2. Ampliación de Calificaciones de Actividades (UC-17, RN-CAL-02, RN-CAL-04, RN-CAL-06)
