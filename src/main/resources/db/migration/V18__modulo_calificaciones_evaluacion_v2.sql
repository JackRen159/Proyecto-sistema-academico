    ADD COLUMN IF NOT EXISTS valor_cualitativo VARCHAR(50),
    ADD COLUMN IF NOT EXISTS observacion_descriptiva TEXT,
    ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0;

DO $$
BEGIN
