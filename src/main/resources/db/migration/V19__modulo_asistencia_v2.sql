-- 1. Ampliación de Registros de Asistencia (UC-19, RN-ASI-07)
ALTER TABLE registros_asistencia
    ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_registros_estado') THEN
        ALTER TABLE registros_asistencia DROP CONSTRAINT chk_registros_estado;
    END IF;

    ALTER TABLE registros_asistencia
        ADD CONSTRAINT chk_registros_estado
        CHECK (estado IN (
            'PRESENTE',
            'AUSENTE_INJUSTIFICADA',
            'AUSENTE_JUSTIFICADA',
            'RETARDO',
            'RETIRO_ANTICIPADO',
            'EVASION_INTERNA_CLASE',
            'SALIDA_ANTICIPADA_AUTORIZADA'
        ));
END $$;

-- 2. Nueva Tabla de Auditoría Inmutable de Asistencia (UC-19, RN-10)
CREATE TABLE IF NOT EXISTS auditoria_asistencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registro_asistencia_id BIGINT NOT NULL,
    matricula_id BIGINT NOT NULL,
    estado_anterior VARCHAR(35),
    estado_nuevo VARCHAR(35) NOT NULL,
    motivo_correccion VARCHAR(255) NOT NULL,
    usuario_id BIGINT,
    username VARCHAR(50) NOT NULL,
    fecha_auditoria TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_auditoria_asistencia_registro FOREIGN KEY (registro_asistencia_id) REFERENCES registros_asistencia (id) ON DELETE CASCADE,
    CONSTRAINT fk_auditoria_asistencia_matricula FOREIGN KEY (matricula_id) REFERENCES matriculas (id) ON DELETE CASCADE,
    CONSTRAINT fk_auditoria_asistencia_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_auditoria_asistencia_reg ON auditoria_asistencia (registro_asistencia_id);
CREATE INDEX IF NOT EXISTS idx_auditoria_asistencia_mat ON auditoria_asistencia (matricula_id);
CREATE INDEX IF NOT EXISTS idx_auditoria_asistencia_fecha ON auditoria_asistencia (fecha_auditoria);

-- 3. Nueva Tabla de Solicitudes de Excusa por Rango de Fechas (UC-PROV-18, RN-ASI-04, RN-ASI-05)
CREATE TABLE IF NOT EXISTS solicitudes_excusa_asistencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_radicado VARCHAR(50) NOT NULL,
    matricula_id BIGINT NOT NULL,
    solicitante_usuario_id BIGINT NOT NULL,
    rol_solicitante VARCHAR(20) NOT NULL,
    tipo_justificacion VARCHAR(35) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    motivo_explicacion TEXT NOT NULL,
    soporte_url VARCHAR(255),
    es_dato_salud_sensible BOOLEAN NOT NULL DEFAULT TRUE,
    estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE_REVISION',
    fecha_radicacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_limite_subsanacion DATE,
    observaciones_resolucion TEXT,
    usuario_resolutor_id BIGINT,
    fecha_resolucion TIMESTAMP(6) WITHOUT TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_solicitud_excusa_radicado UNIQUE (numero_radicado),
    CONSTRAINT fk_solicitud_excusa_matricula FOREIGN KEY (matricula_id) REFERENCES matriculas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_solicitud_excusa_solicitante FOREIGN KEY (solicitante_usuario_id) REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT fk_solicitud_excusa_resolutor FOREIGN KEY (usuario_resolutor_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_solicitud_excusa_rol CHECK (rol_solicitante IN ('ESTUDIANTE', 'ACUDIENTE', 'SECRETARIA')),
    CONSTRAINT chk_solicitud_excusa_tipo CHECK (tipo_justificacion IN (
        'INCAPACIDAD_MEDICA_EPS',
        'CITA_MEDICA',
        'CALAMIDAD_DOMESTICA',
        'FUERZA_MAYOR',
        'REPRESENTACION_INSTITUCIONAL'
    )),
    CONSTRAINT chk_solicitud_excusa_estado CHECK (estado IN (
        'PENDIENTE_REVISION',
        'APROBADA',
        'SUBSANACION_REQUERIDA',
        'RECHAZADA_MOTIVADA'
    )),
    CONSTRAINT chk_solicitud_excusa_rango CHECK (fecha_inicio <= fecha_fin)
);

CREATE INDEX IF NOT EXISTS idx_solicitud_excusa_mat ON solicitudes_excusa_asistencia (matricula_id);
CREATE INDEX IF NOT EXISTS idx_solicitud_excusa_estado ON solicitudes_excusa_asistencia (estado);
CREATE INDEX IF NOT EXISTS idx_solicitud_excusa_fechas ON solicitudes_excusa_asistencia (fecha_inicio, fecha_fin);

-- 4. Nueva Tabla de Autorizaciones de Salida Anticipada en Portería (UC-PROV-18 A1, RN-EST-06, RN-ASI-07)
CREATE TABLE IF NOT EXISTS autorizaciones_salida_anticipada (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_autorizacion VARCHAR(50) NOT NULL,
    matricula_id BIGINT NOT NULL,
    fecha DATE NOT NULL DEFAULT CURRENT_DATE,
    hora_salida VARCHAR(10) NOT NULL,
    motivo VARCHAR(255) NOT NULL,
    adulto_retira_nombre VARCHAR(150) NOT NULL,
    adulto_retira_documento VARCHAR(30) NOT NULL,
    parentesco_autorizado VARCHAR(50) NOT NULL,
    usuario_porteria_validador_id BIGINT,
    estado VARCHAR(35) NOT NULL DEFAULT 'AUTORIZADA_VERIFICADA',
    observaciones VARCHAR(255),
    fecha_registro TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_autorizacion_salida_num UNIQUE (numero_autorizacion),
    CONSTRAINT fk_autorizacion_salida_matricula FOREIGN KEY (matricula_id) REFERENCES matriculas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_autorizacion_salida_porteria FOREIGN KEY (usuario_porteria_validador_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_autorizacion_salida_estado CHECK (estado IN ('AUTORIZADA_VERIFICADA', 'DENEGADA_RESTRICCION_LEGAL'))
);

CREATE INDEX IF NOT EXISTS idx_autorizacion_salida_mat ON autorizaciones_salida_anticipada (matricula_id);
CREATE INDEX IF NOT EXISTS idx_autorizacion_salida_fecha ON autorizaciones_salida_anticipada (fecha);

-- 5. Nueva Tabla de Actuaciones de Seguimiento al Ausentismo y Deserción (UC-PROV-19, RN-ASI-08)
CREATE TABLE IF NOT EXISTS actuaciones_seguimiento_ausentismo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id BIGINT NOT NULL,
    periodo_academico_id BIGINT NOT NULL,
    tipo_actuacion VARCHAR(45) NOT NULL,
    fecha_actuacion DATE NOT NULL DEFAULT CURRENT_DATE,
    descripcion_gestion TEXT NOT NULL,
    compromisos_acordados TEXT,
    soporte_acta_url VARCHAR(255),
    usuario_actuante_id BIGINT,
    fecha_registro TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_actuacion_asistencia_mat FOREIGN KEY (matricula_id) REFERENCES matriculas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_actuacion_asistencia_per FOREIGN KEY (periodo_academico_id) REFERENCES periodos_academicos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_actuacion_asistencia_usr FOREIGN KEY (usuario_actuante_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_actuacion_tipo CHECK (tipo_actuacion IN (
        'CONTACTO_TELEFONICO',
        'CITACION_ACUDIENTE',
        'ACTA_COMPROMISO',
        'VISITA_DOMICILIARIA',
        'CONSTANCIA_PROTOCOLO_DESERCION_AGOTADO'
    ))
);

CREATE INDEX IF NOT EXISTS idx_actuacion_asistencia_mat ON actuaciones_seguimiento_ausentismo (matricula_id);
CREATE INDEX IF NOT EXISTS idx_actuacion_asistencia_per ON actuaciones_seguimiento_ausentismo (periodo_academico_id);
CREATE INDEX IF NOT EXISTS idx_actuacion_asistencia_tipo ON actuaciones_seguimiento_ausentismo (tipo_actuacion);
