-- 1. Tabla de Configuración de Escala SIEE Institucional (por Año Lectivo)
CREATE TABLE IF NOT EXISTS configuraciones_escala_siee (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_lectivo_id BIGINT NOT NULL,
    nota_minima NUMERIC(4,2) NOT NULL DEFAULT 1.00,
    nota_maxima NUMERIC(4,2) NOT NULL DEFAULT 5.00,
    nota_aprobatoria NUMERIC(4,2) NOT NULL DEFAULT 3.00,
    escala_basico_min NUMERIC(4,2) NOT NULL DEFAULT 3.00,
    escala_alto_min NUMERIC(4,2) NOT NULL DEFAULT 4.00,
    escala_superior_min NUMERIC(4,2) NOT NULL DEFAULT 4.60,
    decimales_redondeo INT NOT NULL DEFAULT 1,
    descripcion VARCHAR(255),
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_escala_siee_anio UNIQUE (anio_lectivo_id),
    CONSTRAINT fk_escala_siee_anio FOREIGN KEY (anio_lectivo_id) REFERENCES anios_lectivos (id) ON DELETE RESTRICT,
    CONSTRAINT chk_escala_siee_orden CHECK (
        nota_minima < escala_basico_min AND
        escala_basico_min <= nota_aprobatoria AND
        escala_basico_min < escala_alto_min AND
        escala_alto_min < escala_superior_min AND
        escala_superior_min <= nota_maxima
    ),
    CONSTRAINT chk_escala_siee_decimales CHECK (decimales_redondeo >= 0 AND decimales_redondeo <= 2)
);

CREATE INDEX IF NOT EXISTS idx_escala_siee_anio ON configuraciones_escala_siee (anio_lectivo_id);

-- 2. Tabla de Actividades Evaluativas (creadas por el profesor dentro de su asignación y periodo)
CREATE TABLE IF NOT EXISTS actividades_evaluativas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asignacion_academica_id BIGINT NOT NULL,
    periodo_academico_id BIGINT NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),
    porcentaje NUMERIC(5,2) NOT NULL,
    fecha_evaluacion DATE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_actividades_asignacion FOREIGN KEY (asignacion_academica_id) REFERENCES asignaciones_academicas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_actividades_periodo FOREIGN KEY (periodo_academico_id) REFERENCES periodos_academicos (id) ON DELETE RESTRICT,
    CONSTRAINT chk_actividades_porcentaje CHECK (porcentaje > 0 AND porcentaje <= 100)
);

CREATE INDEX IF NOT EXISTS idx_actividades_asignacion ON actividades_evaluativas (asignacion_academica_id);
CREATE INDEX IF NOT EXISTS idx_actividades_periodo ON actividades_evaluativas (periodo_academico_id);

-- 3. Tabla de Calificaciones de Actividades Evaluativas (por Matrícula de Estudiante)
CREATE TABLE IF NOT EXISTS calificaciones_actividades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actividad_id BIGINT NOT NULL,
    matricula_id BIGINT NOT NULL,
    valor NUMERIC(4,2) NOT NULL,
    observaciones VARCHAR(255),
    fecha_registro TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_calificaciones_actividad_matricula UNIQUE (actividad_id, matricula_id),
    CONSTRAINT fk_calificaciones_actividad FOREIGN KEY (actividad_id) REFERENCES actividades_evaluativas (id) ON DELETE CASCADE,
    CONSTRAINT fk_calificaciones_matricula FOREIGN KEY (matricula_id) REFERENCES matriculas (id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_calificaciones_actividad ON calificaciones_actividades (actividad_id);
CREATE INDEX IF NOT EXISTS idx_calificaciones_matricula ON calificaciones_actividades (matricula_id);

-- 4. Tabla de Calificaciones Definitivas de Periodo
CREATE TABLE IF NOT EXISTS calificaciones_periodo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id BIGINT NOT NULL,
    asignatura_id BIGINT NOT NULL,
    periodo_academico_id BIGINT NOT NULL,
    nota_definitiva NUMERIC(4,2) NOT NULL,
    desempeno VARCHAR(20) NOT NULL,
    aprobada BOOLEAN NOT NULL,
    nota_recuperacion NUMERIC(4,2),
    nota_final NUMERIC(4,2),
    observaciones VARCHAR(255),
    fecha_calculo TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_calif_periodo_mat_asig_per UNIQUE (matricula_id, asignatura_id, periodo_academico_id),
    CONSTRAINT fk_calif_periodo_matricula FOREIGN KEY (matricula_id) REFERENCES matriculas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_calif_periodo_asignatura FOREIGN KEY (asignatura_id) REFERENCES asignaturas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_calif_periodo_periodo FOREIGN KEY (periodo_academico_id) REFERENCES periodos_academicos (id) ON DELETE RESTRICT,
    CONSTRAINT chk_calif_periodo_desempeno CHECK (desempeno IN ('SUPERIOR', 'ALTO', 'BASICO', 'BAJO'))
);

CREATE INDEX IF NOT EXISTS idx_calif_periodo_matricula ON calificaciones_periodo (matricula_id);
CREATE INDEX IF NOT EXISTS idx_calif_periodo_asignatura ON calificaciones_periodo (asignatura_id);
CREATE INDEX IF NOT EXISTS idx_calif_periodo_periodo ON calificaciones_periodo (periodo_academico_id);

-- 5. Tabla de Auditoría Inmutable de Modificaciones de Calificaciones
CREATE TABLE IF NOT EXISTS auditoria_calificaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_entidad VARCHAR(30) NOT NULL,
    entidad_id BIGINT NOT NULL,
    matricula_id BIGINT NOT NULL,
    valor_anterior NUMERIC(4,2),
    valor_nuevo NUMERIC(4,2) NOT NULL,
    motivo VARCHAR(255) NOT NULL,
    usuario_id BIGINT,
    username VARCHAR(50) NOT NULL,
    fecha_auditoria TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_auditoria_calif_matricula FOREIGN KEY (matricula_id) REFERENCES matriculas (id) ON DELETE CASCADE,
    CONSTRAINT fk_auditoria_calif_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_auditoria_tipo CHECK (tipo_entidad IN ('ACTIVIDAD', 'PERIODO'))
);

CREATE INDEX IF NOT EXISTS idx_auditoria_calif_entidad ON auditoria_calificaciones (tipo_entidad, entidad_id);
CREATE INDEX IF NOT EXISTS idx_auditoria_calif_matricula ON auditoria_calificaciones (matricula_id);
CREATE INDEX IF NOT EXISTS idx_auditoria_calif_fecha ON auditoria_calificaciones (fecha_auditoria);
