-- Catálogos de Grados, Áreas, Asignaturas, Años Lectivos, Periodos y Grupos
-- =============================================================================

-- 1. Catálogo de Grados (estructura curricular permanente)
CREATE TABLE IF NOT EXISTS grados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL,
    nombre VARCHAR(50) NOT NULL,
    nivel VARCHAR(30) NOT NULL,
    orden_jerarquico INT NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_grados_codigo UNIQUE (codigo),
    CONSTRAINT uk_grados_orden UNIQUE (orden_jerarquico),
    CONSTRAINT chk_grados_nivel CHECK (nivel IN ('PREESCOLAR', 'BASICA_PRIMARIA', 'BASICA_SECUNDARIA', 'MEDIA'))
);

-- 2. Catálogo de Áreas del Conocimiento (adaptable institucionalmente)
CREATE TABLE IF NOT EXISTS areas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_areas_codigo UNIQUE (codigo),
    CONSTRAINT uk_areas_nombre UNIQUE (nombre)
);

-- 3. Catálogo de Asignaturas (dinámico y extensible según PEI del colegio)
CREATE TABLE IF NOT EXISTS asignaturas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id BIGINT,
    codigo VARCHAR(30) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_asignaturas_codigo UNIQUE (codigo),
    CONSTRAINT fk_asignaturas_area FOREIGN KEY (area_id) REFERENCES areas (id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_asignaturas_area_id ON asignaturas (area_id);

-- 4. Plan de Estudios Base: Relación Grados - Asignaturas
CREATE TABLE IF NOT EXISTS grados_asignaturas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grado_id BIGINT NOT NULL,
    asignatura_id BIGINT NOT NULL,
    intensidad_horaria INT NOT NULL DEFAULT 1,
    es_optativa BOOLEAN NOT NULL DEFAULT FALSE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_grados_asignaturas UNIQUE (grado_id, asignatura_id),
    CONSTRAINT fk_grados_asignaturas_grado FOREIGN KEY (grado_id) REFERENCES grados (id) ON DELETE RESTRICT,
    CONSTRAINT fk_grados_asignaturas_asignatura FOREIGN KEY (asignatura_id) REFERENCES asignaturas (id) ON DELETE RESTRICT,
    CONSTRAINT chk_grados_asignaturas_ih CHECK (intensidad_horaria > 0)
);

CREATE INDEX IF NOT EXISTS idx_grados_asignaturas_grado ON grados_asignaturas (grado_id);
CREATE INDEX IF NOT EXISTS idx_grados_asignaturas_asig ON grados_asignaturas (asignatura_id);

-- 5. Años Lectivos (Vigencias Escolares)
CREATE TABLE IF NOT EXISTS anios_lectivos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio INT NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PLANIFICACION',
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_anios_lectivos_anio UNIQUE (anio),
    CONSTRAINT chk_anios_lectivos_fechas CHECK (fecha_fin >= fecha_inicio),
    CONSTRAINT chk_anios_lectivos_estado CHECK (estado IN ('PLANIFICACION', 'ACTIVO', 'CERRADO'))
);

-- Invariante de regla de negocio: Solo puede existir a lo sumo UN año lectivo ACTIVO
CREATE UNIQUE INDEX IF NOT EXISTS uk_anios_lectivos_unico_activo 
    ON anios_lectivos (estado) 
    WHERE estado = 'ACTIVO';

-- 6. Periodos Académicos
CREATE TABLE IF NOT EXISTS periodos_academicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_lectivo_id BIGINT NOT NULL,
    numero INT NOT NULL,
    nombre VARCHAR(50) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    porcentaje NUMERIC(5,2) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'CERRADO',
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_periodos_anio_numero UNIQUE (anio_lectivo_id, numero),
    CONSTRAINT fk_periodos_anio_lectivo FOREIGN KEY (anio_lectivo_id) REFERENCES anios_lectivos (id) ON DELETE RESTRICT,
    CONSTRAINT chk_periodos_fechas CHECK (fecha_fin >= fecha_inicio),
    CONSTRAINT chk_periodos_porcentaje CHECK (porcentaje > 0 AND porcentaje <= 100),
    CONSTRAINT chk_periodos_estado CHECK (estado IN ('ABIERTO', 'CERRADO'))
);

CREATE INDEX IF NOT EXISTS idx_periodos_anio_lectivo_id ON periodos_academicos (anio_lectivo_id);

-- 7. Grupos / Cursos por Vigencia
CREATE TABLE IF NOT EXISTS grupos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_lectivo_id BIGINT NOT NULL,
    grado_id BIGINT NOT NULL,
    nombre VARCHAR(20) NOT NULL,
    jornada VARCHAR(20) NOT NULL DEFAULT 'MANANA',
    cupo_maximo INT NOT NULL DEFAULT 35,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_grupos_anio_grado_nombre UNIQUE (anio_lectivo_id, grado_id, nombre),
    CONSTRAINT fk_grupos_anio_lectivo FOREIGN KEY (anio_lectivo_id) REFERENCES anios_lectivos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_grupos_grado FOREIGN KEY (grado_id) REFERENCES grados (id) ON DELETE RESTRICT,
    CONSTRAINT chk_grupos_jornada CHECK (jornada IN ('MANANA', 'TARDE', 'UNICA', 'NOCTURNA', 'COMPLETA')),
    CONSTRAINT chk_grupos_cupo CHECK (cupo_maximo > 0)
);

CREATE INDEX IF NOT EXISTS idx_grupos_anio_lectivo ON grupos (anio_lectivo_id);
CREATE INDEX IF NOT EXISTS idx_grupos_grado ON grupos (grado_id);

