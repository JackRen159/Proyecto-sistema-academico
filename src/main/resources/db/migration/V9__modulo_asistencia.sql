-- 1. Tabla de Configuración de Alertas de Asistencia por Año Lectivo
CREATE TABLE IF NOT EXISTS configuraciones_alerta_asistencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_lectivo_id BIGINT NOT NULL,
    porcentaje_alerta_amarilla NUMERIC(5,2) NOT NULL DEFAULT 15.00,
    porcentaje_alerta_roja NUMERIC(5,2) NOT NULL DEFAULT 25.00,
    descripcion VARCHAR(255),
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_alerta_asistencia_anio UNIQUE (anio_lectivo_id),
    CONSTRAINT fk_alerta_asistencia_anio FOREIGN KEY (anio_lectivo_id) REFERENCES anios_lectivos (id) ON DELETE RESTRICT,
    CONSTRAINT chk_alerta_asistencia_rango CHECK (
        porcentaje_alerta_amarilla > 0 AND
        porcentaje_alerta_amarilla < porcentaje_alerta_roja AND
        porcentaje_alerta_roja <= 100
    )
);

CREATE INDEX IF NOT EXISTS idx_alerta_asistencia_anio ON configuraciones_alerta_asistencia (anio_lectivo_id);

-- 2. Tabla de Sesiones de Asistencia (por asignatura o por jornada general)
CREATE TABLE IF NOT EXISTS sesiones_asistencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asignacion_academica_id BIGINT,
    grupo_id BIGINT NOT NULL,
    periodo_academico_id BIGINT NOT NULL,
    fecha DATE NOT NULL DEFAULT CURRENT_DATE,
    bloque_horario INT NOT NULL DEFAULT 1,
    tipo_registro VARCHAR(30) NOT NULL DEFAULT 'SESION_ASIGNATURA',
    tema VARCHAR(150),
    observaciones VARCHAR(255),
    usuario_creador_id BIGINT,
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_sesiones_asignacion FOREIGN KEY (asignacion_academica_id) REFERENCES asignaciones_academicas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sesiones_grupo FOREIGN KEY (grupo_id) REFERENCES grupos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sesiones_periodo FOREIGN KEY (periodo_academico_id) REFERENCES periodos_academicos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sesiones_usuario FOREIGN KEY (usuario_creador_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_sesiones_tipo CHECK (tipo_registro IN ('SESION_ASIGNATURA', 'DIARIA_JORNADA')),
    CONSTRAINT chk_sesiones_bloque CHECK (bloque_horario > 0)
);

-- Unicidad condicional para sesiones de clase por asignatura
CREATE UNIQUE INDEX IF NOT EXISTS uk_sesion_asignacion_fecha_bloque
    ON sesiones_asistencia (asignacion_academica_id, fecha, bloque_horario)
    WHERE tipo_registro = 'SESION_ASIGNATURA';

-- Unicidad condicional para registro de jornada diaria general
CREATE UNIQUE INDEX IF NOT EXISTS uk_sesion_diaria_grupo_fecha
    ON sesiones_asistencia (grupo_id, fecha)
    WHERE tipo_registro = 'DIARIA_JORNADA';

CREATE INDEX IF NOT EXISTS idx_sesiones_grupo ON sesiones_asistencia (grupo_id);
CREATE INDEX IF NOT EXISTS idx_sesiones_asignacion ON sesiones_asistencia (asignacion_academica_id);
CREATE INDEX IF NOT EXISTS idx_sesiones_periodo ON sesiones_asistencia (periodo_academico_id);
CREATE INDEX IF NOT EXISTS idx_sesiones_fecha ON sesiones_asistencia (fecha);

-- 3. Tabla de Registros Individuales de Asistencia (Planilla por Estudiante)
CREATE TABLE IF NOT EXISTS registros_asistencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sesion_asistencia_id BIGINT NOT NULL,
    matricula_id BIGINT NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'PRESENTE',
    minutos_retardo INT NOT NULL DEFAULT 0,
    observaciones VARCHAR(255),
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_registro_asistencia_sesion_matricula UNIQUE (sesion_asistencia_id, matricula_id),
    CONSTRAINT fk_registros_sesion FOREIGN KEY (sesion_asistencia_id) REFERENCES sesiones_asistencia (id) ON DELETE CASCADE,
    CONSTRAINT fk_registros_matricula FOREIGN KEY (matricula_id) REFERENCES matriculas (id) ON DELETE RESTRICT,
    CONSTRAINT chk_registros_estado CHECK (estado IN ('PRESENTE', 'AUSENTE_INJUSTIFICADA', 'AUSENTE_JUSTIFICADA', 'RETARDO', 'RETIRO_ANTICIPADO')),
    CONSTRAINT chk_registros_retardo CHECK (minutos_retardo >= 0)
);

CREATE INDEX IF NOT EXISTS idx_registros_sesion ON registros_asistencia (sesion_asistencia_id);
CREATE INDEX IF NOT EXISTS idx_registros_matricula ON registros_asistencia (matricula_id);
CREATE INDEX IF NOT EXISTS idx_registros_estado ON registros_asistencia (estado);

-- 4. Tabla de Justificaciones de Inasistencia (Auditoría Inmutable)
CREATE TABLE IF NOT EXISTS justificaciones_asistencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registro_asistencia_id BIGINT NOT NULL,
    motivo VARCHAR(255) NOT NULL,
    numero_radicado_soporte VARCHAR(50),
    fecha_radicacion DATE NOT NULL DEFAULT CURRENT_DATE,
    usuario_autorizador_id BIGINT,
    username VARCHAR(50) NOT NULL,
    observaciones VARCHAR(255),
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_justificacion_registro UNIQUE (registro_asistencia_id),
    CONSTRAINT fk_justificaciones_registro FOREIGN KEY (registro_asistencia_id) REFERENCES registros_asistencia (id) ON DELETE CASCADE,
    CONSTRAINT fk_justificaciones_usuario FOREIGN KEY (usuario_autorizador_id) REFERENCES usuarios (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_justificaciones_registro ON justificaciones_asistencia (registro_asistencia_id);
CREATE INDEX IF NOT EXISTS idx_justificaciones_fecha ON justificaciones_asistencia (fecha_radicacion);
