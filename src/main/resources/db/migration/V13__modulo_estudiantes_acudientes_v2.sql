-- 1. Ampliación de la tabla `estudiantes` con campos normativos colombianos
ALTER TABLE estudiantes
    ADD COLUMN IF NOT EXISTS tipo_documento VARCHAR(20) NOT NULL DEFAULT 'TI',
    ADD COLUMN IF NOT EXISTS sexo VARCHAR(20) NOT NULL DEFAULT 'NO_ESPECIFICADO',
    ADD COLUMN IF NOT EXISTS eps VARCHAR(100) NOT NULL DEFAULT 'Sin asegurar / En trámite',
    ADD COLUMN IF NOT EXISTS grupo_sanguineo_rh VARCHAR(10) NOT NULL DEFAULT 'O+',
    ADD COLUMN IF NOT EXISTS tiene_discapacidad_piar BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS detalles_salud_emergencia TEXT,
    ADD COLUMN IF NOT EXISTS estado_expediente VARCHAR(30) NOT NULL DEFAULT 'LISTO_PARA_MATRICULA';

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_estudiantes_tipo_doc') THEN
        ALTER TABLE estudiantes
            ADD CONSTRAINT chk_estudiantes_tipo_doc
            CHECK (tipo_documento IN ('RC', 'TI', 'CC', 'CE', 'PPT', 'PEP', 'NES'));
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_estudiantes_sexo') THEN
        ALTER TABLE estudiantes
            ADD CONSTRAINT chk_estudiantes_sexo
            CHECK (sexo IN ('MASCULINO', 'FEMENINO', 'OTRO', 'NO_ESPECIFICADO'));
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_estudiantes_estado_exp') THEN
        ALTER TABLE estudiantes
            ADD CONSTRAINT chk_estudiantes_estado_exp
            CHECK (estado_expediente IN ('BORRADOR_PENDIENTE', 'LISTO_PARA_MATRICULA', 'MATRICULADO', 'INACTIVO_HISTORICO'));
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_estudiantes_tipo_doc ON estudiantes (tipo_documento);
CREATE INDEX IF NOT EXISTS idx_estudiantes_estado_exp ON estudiantes (estado_expediente);

-- 2. Ampliación de la tabla `acudientes` con tipificación documental y fecha de nacimiento
ALTER TABLE acudientes
    ADD COLUMN IF NOT EXISTS tipo_documento VARCHAR(20) NOT NULL DEFAULT 'CC',
    ADD COLUMN IF NOT EXISTS fecha_nacimiento DATE;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_acudientes_tipo_doc') THEN
        ALTER TABLE acudientes
            ADD CONSTRAINT chk_acudientes_tipo_doc
            CHECK (tipo_documento IN ('CC', 'CE', 'PPT', 'PEP', 'TI', 'PASAPORTE'));
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_acudientes_tipo_doc ON acudientes (tipo_documento);

-- 3. Ampliación de `estudiante_acudiente` (RN-EST-02, RN-EST-06, RN-EST-07)
ALTER TABLE estudiante_acudiente
    ADD COLUMN IF NOT EXISTS estado_vinculo VARCHAR(30) NOT NULL DEFAULT 'VERIFICADO',
    ADD COLUMN IF NOT EXISTS tiene_custodia BOOLEAN NOT NULL DEFAULT TRUE,
    ADD COLUMN IF NOT EXISTS representacion_legal BOOLEAN NOT NULL DEFAULT TRUE,
    ADD COLUMN IF NOT EXISTS prioridad_emergencia INT NOT NULL DEFAULT 1,
    ADD COLUMN IF NOT EXISTS motivo_bloqueo_legal VARCHAR(500),
    ADD COLUMN IF NOT EXISTS fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW();

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_est_acud_estado_vinculo') THEN
        ALTER TABLE estudiante_acudiente
            ADD CONSTRAINT chk_est_acud_estado_vinculo
            CHECK (estado_vinculo IN ('VERIFICADO', 'PENDIENTE_VERIFICACION', 'EN_DISPUTA', 'REVOCADO', 'BLOQUEADO_RESTRICCION_LEGAL'));
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_est_acud_estado ON estudiante_acudiente (estado_vinculo);

-- 4. Tabla de Historial Inmutable de Documentos de Identidad (UC-PROV-04 A1, RN-EST-03)
CREATE TABLE IF NOT EXISTS historial_documentos_identidad (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL,
    tipo_documento_anterior VARCHAR(20) NOT NULL,
    numero_documento_anterior VARCHAR(20) NOT NULL,
    tipo_documento_nuevo VARCHAR(20) NOT NULL,
    numero_documento_nuevo VARCHAR(20) NOT NULL,
    fecha_cambio TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    motivo_cambio VARCHAR(255) NOT NULL,
    soporte_documento_url VARCHAR(255),
    usuario_autorizador_id BIGINT,
    CONSTRAINT fk_historial_doc_estudiante FOREIGN KEY (estudiante_id) REFERENCES estudiantes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_historial_doc_autorizador FOREIGN KEY (usuario_autorizador_id) REFERENCES usuarios (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_historial_doc_estudiante ON historial_documentos_identidad (estudiante_id);
CREATE INDEX IF NOT EXISTS idx_historial_doc_anterior ON historial_documentos_identidad (numero_documento_anterior);

-- 5. Tabla de Solicitudes de Rectificación de Datos - Habeas Data (UC-07 A2, UC-PROV-04, RN-EST-04)
CREATE TABLE IF NOT EXISTS solicitudes_rectificacion_habeas_data (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_radicado VARCHAR(50) NOT NULL UNIQUE,
    estudiante_id BIGINT NOT NULL,
    usuario_solicitante_id BIGINT NOT NULL,
    campos_a_modificar_json TEXT NOT NULL,
    motivo_solicitud VARCHAR(500) NOT NULL,
    soporte_url VARCHAR(255),
    fecha_radicacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_limite_legal DATE NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE',
    respuesta_motivada TEXT,
    fecha_resolucion TIMESTAMP(6) WITHOUT TIME ZONE,
    usuario_resolutor_id BIGINT,
    CONSTRAINT fk_rectificacion_estudiante FOREIGN KEY (estudiante_id) REFERENCES estudiantes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_rectificacion_solicitante FOREIGN KEY (usuario_solicitante_id) REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT fk_rectificacion_resolutor FOREIGN KEY (usuario_resolutor_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_rectificacion_estado CHECK (estado IN ('PENDIENTE', 'EN_TRAMITE', 'APROBADA', 'RECHAZADA_MOTIVADA'))
);

CREATE INDEX IF NOT EXISTS idx_rectificacion_estudiante ON solicitudes_rectificacion_habeas_data (estudiante_id);
CREATE INDEX IF NOT EXISTS idx_rectificacion_estado ON solicitudes_rectificacion_habeas_data (estado);

-- 6. Tabla de Autorizaciones de Tratamiento de Datos del Menor (RN-EST-01, UC-12 paso 6)
CREATE TABLE IF NOT EXISTS autorizaciones_tratamiento_datos_menor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL,
    acudiente_id BIGINT,
    politica_id BIGINT NOT NULL,
    autoriza_finalidades_educativas_obligatorias BOOLEAN NOT NULL DEFAULT TRUE,
    autoriza_uso_imagen_fotografia_opcional BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_autorizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    direccion_ip VARCHAR(45),
    user_agent VARCHAR(255),
    CONSTRAINT fk_aut_menor_estudiante FOREIGN KEY (estudiante_id) REFERENCES estudiantes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_aut_menor_acudiente FOREIGN KEY (acudiente_id) REFERENCES acudientes (id) ON DELETE SET NULL,
    CONSTRAINT fk_aut_menor_politica FOREIGN KEY (politica_id) REFERENCES politica_tratamiento_datos (id) ON DELETE RESTRICT,
    CONSTRAINT uk_autorizacion_menor_politica UNIQUE (estudiante_id, politica_id)
);

CREATE INDEX IF NOT EXISTS idx_aut_menor_estudiante ON autorizaciones_tratamiento_datos_menor (estudiante_id);
