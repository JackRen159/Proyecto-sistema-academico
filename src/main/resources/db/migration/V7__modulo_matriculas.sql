-- 1. Tabla de Matrículas
CREATE TABLE IF NOT EXISTS matriculas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_matricula VARCHAR(30) NOT NULL,
    estudiante_id BIGINT NOT NULL,
    grupo_id BIGINT NOT NULL,
    anio_lectivo_id BIGINT NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'MATRICULADA',
    tipo_matricula VARCHAR(25) NOT NULL DEFAULT 'REGULAR',
    folio VARCHAR(30),
    fecha_matricula DATE NOT NULL DEFAULT CURRENT_DATE,
    observaciones VARCHAR(255),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_matriculas_numero UNIQUE (numero_matricula),
    CONSTRAINT fk_matriculas_estudiante FOREIGN KEY (estudiante_id) REFERENCES estudiantes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_matriculas_grupo FOREIGN KEY (grupo_id) REFERENCES grupos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_matriculas_anio_lectivo FOREIGN KEY (anio_lectivo_id) REFERENCES anios_lectivos (id) ON DELETE RESTRICT,
    CONSTRAINT chk_matriculas_estado CHECK (estado IN ('INSCRITA', 'MATRICULADA', 'RETIRADA', 'FINALIZADA')),
    CONSTRAINT chk_matriculas_tipo CHECK (tipo_matricula IN ('REGULAR', 'NUEVO', 'REINCORPORADO', 'TRASLADO_EXTERNO'))
);

-- Invariante de negocio: Un estudiante solo puede tener a lo sumo UNA matrícula activa en un mismo año lectivo
CREATE UNIQUE INDEX IF NOT EXISTS uk_matriculas_estudiante_anio_activo
    ON matriculas (estudiante_id, anio_lectivo_id)
    WHERE estado = 'MATRICULADA';

CREATE INDEX IF NOT EXISTS idx_matriculas_estudiante ON matriculas (estudiante_id);
CREATE INDEX IF NOT EXISTS idx_matriculas_grupo ON matriculas (grupo_id);
CREATE INDEX IF NOT EXISTS idx_matriculas_anio_lectivo ON matriculas (anio_lectivo_id);
CREATE INDEX IF NOT EXISTS idx_matriculas_estado ON matriculas (estado);

-- 2. Tabla de Historial de Traslados de Grupo
CREATE TABLE IF NOT EXISTS historial_traslados_matricula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id BIGINT NOT NULL,
    grupo_origen_id BIGINT NOT NULL,
    grupo_destino_id BIGINT NOT NULL,
    motivo VARCHAR(255) NOT NULL,
    usuario_id BIGINT,
    fecha_traslado TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_traslados_matricula FOREIGN KEY (matricula_id) REFERENCES matriculas (id) ON DELETE CASCADE,
    CONSTRAINT fk_traslados_grupo_origen FOREIGN KEY (grupo_origen_id) REFERENCES grupos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_traslados_grupo_destino FOREIGN KEY (grupo_destino_id) REFERENCES grupos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_traslados_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_traslados_matricula ON historial_traslados_matricula (matricula_id);
CREATE INDEX IF NOT EXISTS idx_traslados_fecha ON historial_traslados_matricula (fecha_traslado);
