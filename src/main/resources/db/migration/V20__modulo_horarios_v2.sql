-- 1. Catálogo de Aulas y Espacios Físicos por Sede (UC-PROV-20, RN-HOR-05)
CREATE TABLE IF NOT EXISTS aulas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sede VARCHAR(50) NOT NULL DEFAULT 'SEDE_PRINCIPAL',
    codigo VARCHAR(20) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    tipo_espacio VARCHAR(35) NOT NULL DEFAULT 'AULA_ESTANDAR',
    capacidad_maxima INT NOT NULL DEFAULT 40,
    es_multigrupo BOOLEAN NOT NULL DEFAULT FALSE,
    estado VARCHAR(25) NOT NULL DEFAULT 'DISPONIBLE',
    observaciones VARCHAR(255),
    version BIGINT NOT NULL DEFAULT 0,
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_aula_sede_codigo UNIQUE (sede, codigo),
    CONSTRAINT chk_aula_tipo CHECK (tipo_espacio IN (
        'AULA_ESTANDAR',
        'LABORATORIO_CIENCIAS',
        'SALA_INFORMATICA',
        'AULA_POLIVALENTE',
        'ESCENARIO_DEPORTIVO',
        'AUDITORIO'
    )),
    CONSTRAINT chk_aula_estado CHECK (estado IN ('DISPONIBLE', 'EN_MANTENIMIENTO', 'INACTIVA')),
    CONSTRAINT chk_aula_capacidad CHECK (capacidad_maxima > 0)
);

CREATE INDEX IF NOT EXISTS idx_aulas_sede ON aulas (sede);
CREATE INDEX IF NOT EXISTS idx_aulas_tipo ON aulas (tipo_espacio);
CREATE INDEX IF NOT EXISTS idx_aulas_estado ON aulas (estado);

-- 2. Plantillas de Franjas Horarias por Jornada y Año Lectivo (UC-PROV-20, Dec. 1850/2002, RN-HOR-04)
CREATE TABLE IF NOT EXISTS plantillas_franja_horaria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_lectivo_id BIGINT NOT NULL,
    jornada VARCHAR(20) NOT NULL,
    numero_bloque INT NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    tipo_franja VARCHAR(30) NOT NULL DEFAULT 'BLOQUE_LECTIVO',
    descripcion VARCHAR(100),
    CONSTRAINT uk_franja_anio_jornada_bloque UNIQUE (anio_lectivo_id, jornada, numero_bloque),
    CONSTRAINT fk_franja_anio FOREIGN KEY (anio_lectivo_id) REFERENCES anios_lectivos (id) ON DELETE RESTRICT,
    CONSTRAINT chk_franja_jornada CHECK (jornada IN ('MANANA', 'TARDE', 'NOCHE', 'UNICA', 'COMPLETA')),
    CONSTRAINT chk_franja_tipo CHECK (tipo_franja IN ('BLOQUE_LECTIVO', 'DESCANSO_PEDAGOGICO', 'DIRECCION_GRUPO')),
    CONSTRAINT chk_franja_horas CHECK (hora_inicio < hora_fin),
    CONSTRAINT chk_franja_bloque CHECK (numero_bloque > 0)
);

CREATE INDEX IF NOT EXISTS idx_franjas_anio_jornada ON plantillas_franja_horaria (anio_lectivo_id, jornada);

-- 3. Versionamiento de Horarios por Grupo (UC-PROV-20, RN-HOR-06)
CREATE TABLE IF NOT EXISTS horarios_grupo_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id BIGINT NOT NULL,
    numero_version INT NOT NULL DEFAULT 1,
    estado VARCHAR(25) NOT NULL DEFAULT 'BORRADOR',
    fecha_inicio_vigencia DATE,
    fecha_fin_vigencia DATE,
    usuario_publicador_id BIGINT,
    fecha_publicacion TIMESTAMP(6) WITHOUT TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_horario_grupo_version UNIQUE (grupo_id, numero_version),
    CONSTRAINT fk_horario_version_grupo FOREIGN KEY (grupo_id) REFERENCES grupos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_horario_version_usuario FOREIGN KEY (usuario_publicador_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_horario_version_estado CHECK (estado IN ('BORRADOR', 'PUBLICADO_VIGENTE', 'HISTORICO'))
);

CREATE INDEX IF NOT EXISTS idx_horario_version_grupo ON horarios_grupo_version (grupo_id);
CREATE INDEX IF NOT EXISTS idx_horario_version_estado ON horarios_grupo_version (estado);
CREATE INDEX IF NOT EXISTS idx_horario_version_vigencia ON horarios_grupo_version (fecha_inicio_vigencia, fecha_fin_vigencia);

-- 4. Grilla de Bloques Horarios con Triple No-Colisión (UC-PROV-20, RN-HOR-01, RN-HOR-02, RN-HOR-03)
CREATE TABLE IF NOT EXISTS horarios_bloques (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    horario_version_id BIGINT NOT NULL,
    asignacion_academica_id BIGINT NOT NULL,
    aula_id BIGINT NOT NULL,
    dia_semana VARCHAR(15) NOT NULL,
    franja_horaria_id BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_bloque_version_dia_franja UNIQUE (horario_version_id, dia_semana, franja_horaria_id),
    CONSTRAINT fk_bloque_horario_version FOREIGN KEY (horario_version_id) REFERENCES horarios_grupo_version (id) ON DELETE CASCADE,
    CONSTRAINT fk_bloque_asignacion FOREIGN KEY (asignacion_academica_id) REFERENCES asignaciones_academicas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_bloque_aula FOREIGN KEY (aula_id) REFERENCES aulas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_bloque_franja FOREIGN KEY (franja_horaria_id) REFERENCES plantillas_franja_horaria (id) ON DELETE RESTRICT,
    CONSTRAINT chk_bloque_dia CHECK (dia_semana IN ('LUNES', 'MARTES', 'MIERCOLES', 'JUEVES', 'VIERNES', 'SABADO'))
);

CREATE INDEX IF NOT EXISTS idx_bloques_version ON horarios_bloques (horario_version_id);
CREATE INDEX IF NOT EXISTS idx_bloques_asignacion ON horarios_bloques (asignacion_academica_id);
CREATE INDEX IF NOT EXISTS idx_bloques_aula ON horarios_bloques (aula_id);
CREATE INDEX IF NOT EXISTS idx_bloques_dia_franja ON horarios_bloques (dia_semana, franja_horaria_id);

-- 5. Novedades Temporales de Horario y Reasignaciones (UC-PROV-21, RN-HOR-06)
CREATE TABLE IF NOT EXISTS novedades_horario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    horario_bloque_id BIGINT NOT NULL,
    tipo_novedad VARCHAR(35) NOT NULL,
    aula_reemplazo_id BIGINT,
    docente_reemplazo_id BIGINT,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    motivo TEXT NOT NULL,
    usuario_autorizador_id BIGINT,
    fecha_registro TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_novedad_bloque FOREIGN KEY (horario_bloque_id) REFERENCES horarios_bloques (id) ON DELETE CASCADE,
    CONSTRAINT fk_novedad_aula FOREIGN KEY (aula_reemplazo_id) REFERENCES aulas (id) ON DELETE SET NULL,
    CONSTRAINT fk_novedad_docente FOREIGN KEY (docente_reemplazo_id) REFERENCES profesores (id) ON DELETE SET NULL,
    CONSTRAINT fk_novedad_usuario FOREIGN KEY (usuario_autorizador_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_novedad_tipo CHECK (tipo_novedad IN (
        'CAMBIO_AULA_TEMPORAL',
        'PERMUTA_DOCENTE',
        'JORNADA_ESPECIAL',
        'SUPLENCIA_DOCENTE'
    )),
    CONSTRAINT chk_novedad_rango CHECK (fecha_inicio <= fecha_fin)
);

CREATE INDEX IF NOT EXISTS idx_novedades_bloque ON novedades_horario (horario_bloque_id);
CREATE INDEX IF NOT EXISTS idx_novedades_fechas ON novedades_horario (fecha_inicio, fecha_fin);

