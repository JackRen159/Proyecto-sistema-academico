-- 1. Ampliación de la tabla `usuarios` para ciclo de vida completo V2
ALTER TABLE usuarios
    ADD COLUMN IF NOT EXISTS estado VARCHAR(30) NOT NULL DEFAULT 'ACTIVA',
    ADD COLUMN IF NOT EXISTS debe_cambiar_password BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS intentos_fallidos INT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS bloqueado_hasta TIMESTAMP(6) WITHOUT TIME ZONE,
    ADD COLUMN IF NOT EXISTS fecha_ultimo_cambio_password TIMESTAMP(6) WITHOUT TIME ZONE,
    ADD COLUMN IF NOT EXISTS persona_tipo VARCHAR(30),
    ADD COLUMN IF NOT EXISTS persona_id BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'chk_usuarios_estado'
    ) THEN
        ALTER TABLE usuarios
            ADD CONSTRAINT chk_usuarios_estado
            CHECK (estado IN ('ACTIVA', 'PENDIENTE_ACTIVACION', 'BLOQUEADA', 'INACTIVA', 'INACTIVA_HISTORICA'));
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'chk_usuarios_persona_tipo'
    ) THEN
        ALTER TABLE usuarios
            ADD CONSTRAINT chk_usuarios_persona_tipo
            CHECK (persona_tipo IS NULL OR persona_tipo IN ('ESTUDIANTE', 'ACUDIENTE', 'PROFESOR', 'ADMINISTRATIVO'));
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_usuarios_estado ON usuarios (estado);
CREATE INDEX IF NOT EXISTS idx_usuarios_persona ON usuarios (persona_tipo, persona_id);

-- 2. Tabla de Asignación de Roles Múltiples con Vigencia Temporal (UC-PROV-02, RN-SEG-04)
CREATE TABLE IF NOT EXISTS usuario_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    rol VARCHAR(30) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    es_principal BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_inicio DATE NOT NULL DEFAULT CURRENT_DATE,
    fecha_fin DATE,
    anio_lectivo_id BIGINT,
    motivo_asignacion VARCHAR(255),
    asignado_por_id BIGINT,
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_usuario_roles_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT fk_usuario_roles_anio FOREIGN KEY (anio_lectivo_id) REFERENCES anios_lectivos (id) ON DELETE SET NULL,
    CONSTRAINT fk_usuario_roles_asignador FOREIGN KEY (asignado_por_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_usuario_roles_rol CHECK (rol IN (
        'ADMINISTRADOR',
        'RECTOR',
        'COORDINADOR',
        'COORDINADOR_ACADEMICO',
        'COORDINADOR_CONVIVENCIA',
        'ORIENTADOR_ESCOLAR',
        'PROFESOR',
        'ESTUDIANTE',
        'ACUDIENTE',
        'SECRETARIA'
    ))
);

CREATE INDEX IF NOT EXISTS idx_usuario_roles_usuario ON usuario_roles (usuario_id);
CREATE INDEX IF NOT EXISTS idx_usuario_roles_rol ON usuario_roles (rol);
CREATE INDEX IF NOT EXISTS idx_usuario_roles_activo ON usuario_roles (usuario_id, activo);

-- 3. Tabla de Miembros Nominativos de Órganos Colegiados (UC-PROV-02 A2, RN-SEG-01)
CREATE TABLE IF NOT EXISTS organos_colegiados_miembros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    tipo_organo VARCHAR(50) NOT NULL,
    acta_designacion VARCHAR(100) NOT NULL,
    anio_lectivo_id BIGINT NOT NULL,
    fecha_inicio DATE NOT NULL DEFAULT CURRENT_DATE,
    fecha_fin DATE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    motivo VARCHAR(255),
    designado_por_id BIGINT,
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_organos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT fk_organos_anio FOREIGN KEY (anio_lectivo_id) REFERENCES anios_lectivos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_organos_designador FOREIGN KEY (designado_por_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT uk_organo_usuario_anio UNIQUE (tipo_organo, usuario_id, anio_lectivo_id),
    CONSTRAINT chk_organo_tipo CHECK (tipo_organo IN (
        'COMISION_EVALUACION_PROMOCION',
        'COMITE_CONVIVENCIA',
        'CONSEJO_ACADEMICO',
        'CONSEJO_DIRECTIVO'
    ))
);

CREATE INDEX IF NOT EXISTS idx_organos_usuario ON organos_colegiados_miembros (usuario_id);
CREATE INDEX IF NOT EXISTS idx_organos_tipo_anio ON organos_colegiados_miembros (tipo_organo, anio_lectivo_id);

-- 4. Tabla de Tokens de Recuperación de Contraseña de un Solo Uso (UC-PROV-03)
CREATE TABLE IF NOT EXISTS tokens_recuperacion_password (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    usado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_expiracion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_uso TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT fk_tokens_recuperacion_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT uk_token_recuperacion_hash UNIQUE (token_hash)
);

CREATE INDEX IF NOT EXISTS idx_token_recuperacion_usuario ON tokens_recuperacion_password (usuario_id);
CREATE INDEX IF NOT EXISTS idx_token_recuperacion_expiracion ON tokens_recuperacion_password (fecha_expiracion);

-- 5. Migración de Datos Existentes: Sembrar rol principal en `usuario_roles` para usuarios previos
INSERT INTO usuario_roles (usuario_id, rol, activo, es_principal, fecha_inicio, motivo_asignacion)
SELECT
    u.id,
    u.rol,
    u.activo,
    TRUE,
    CURRENT_DATE,
    'Migracion automatica V11 de rol principal previo'
FROM usuarios u
WHERE NOT EXISTS (
    SELECT 1 FROM usuario_roles ur WHERE ur.usuario_id = u.id AND ur.rol = u.rol
);
