-- 1. Tablas de Retención Documental (TRD) conforme a la Ley 594 de 2000
CREATE TABLE IF NOT EXISTS tablas_retencion_documental (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_serie VARCHAR(30) NOT NULL UNIQUE,
    nombre_serie VARCHAR(150) NOT NULL,
    subserie VARCHAR(150),
    anios_retencion_gestion INT NOT NULL DEFAULT 2,
    anios_retencion_central INT NOT NULL DEFAULT 5,
    disposicion_final VARCHAR(40) NOT NULL DEFAULT 'CONSERVACION_TOTAL',
    procedimiento_seguridad TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_registro TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT chk_trd_disposicion CHECK (disposicion_final IN (
        'CONSERVACION_TOTAL',
        'ELIMINACION_REGULADA',
        'MICROFILMACION_DIGITAL'
    ))
);

CREATE INDEX IF NOT EXISTS idx_trd_serie ON tablas_retencion_documental (codigo_serie);

-- 2. Repositorio Documental Centralizado y Seguro (UC-PROV-28, RN-DOC-05)
CREATE TABLE IF NOT EXISTS repositorio_documentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_documento VARCHAR(60) NOT NULL UNIQUE,
    titulo VARCHAR(200) NOT NULL,
    descripcion TEXT,
    tipo_documento VARCHAR(50) NOT NULL,
    nivel_confidencialidad VARCHAR(45) NOT NULL DEFAULT 'ACADEMICO_ESTANDAR',
    estado_ciclo_vida VARCHAR(40) NOT NULL DEFAULT 'EN_REVISION',
    estudiante_id BIGINT,
    matricula_id BIGINT,
    anio_lectivo_id BIGINT,
    trd_id BIGINT,
    version_actual INT NOT NULL DEFAULT 1,
    hash_sha256_actual VARCHAR(64) NOT NULL,
    ruta_almacenamiento VARCHAR(255) NOT NULL,
    nombre_archivo_original VARCHAR(255) NOT NULL,
    mime_type VARCHAR(100) NOT NULL DEFAULT 'application/pdf',
    tamano_bytes BIGINT NOT NULL,
    usuario_creador_id BIGINT NOT NULL,
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_publicacion TIMESTAMP(6) WITHOUT TIME ZONE,
    motivo_anulacion TEXT,
    usuario_anulador_id BIGINT,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_rep_doc_estudiante FOREIGN KEY (estudiante_id) REFERENCES estudiantes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_rep_doc_matricula FOREIGN KEY (matricula_id) REFERENCES matriculas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_rep_doc_anio FOREIGN KEY (anio_lectivo_id) REFERENCES anios_lectivos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_rep_doc_trd FOREIGN KEY (trd_id) REFERENCES tablas_retencion_documental (id) ON DELETE SET NULL,
    CONSTRAINT fk_rep_doc_creador FOREIGN KEY (usuario_creador_id) REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT fk_rep_doc_anulador FOREIGN KEY (usuario_anulador_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_rep_doc_confidencialidad CHECK (nivel_confidencialidad IN (
        'PUBLICO_INSTITUCIONAL',
        'ACADEMICO_ESTANDAR',
        'ADMINISTRATIVO_EXPEDIENTE',
        'CONFIDENCIAL_SALUD_E_INCLUSION',
        'RESERVADO_CONVIVENCIA_Y_PROTECCION'
    )),
    CONSTRAINT chk_rep_doc_estado CHECK (estado_ciclo_vida IN (
        'EN_REVISION',
        'PUBLICADO_VIGENTE',
        'HISTORICO_REEMPLAZADO',
        'ANULADO_MOTIVADO'
    ))
);

CREATE INDEX IF NOT EXISTS idx_rep_doc_codigo ON repositorio_documentos (codigo_documento);
CREATE INDEX IF NOT EXISTS idx_rep_doc_est ON repositorio_documentos (estudiante_id);
CREATE INDEX IF NOT EXISTS idx_rep_doc_tipo ON repositorio_documentos (tipo_documento);
CREATE INDEX IF NOT EXISTS idx_rep_doc_conf ON repositorio_documentos (nivel_confidencialidad);
CREATE INDEX IF NOT EXISTS idx_rep_doc_estado ON repositorio_documentos (estado_ciclo_vida);

-- 3. Versiones Inmutables de Documentos en Repositorio (UC-PROV-28 A1)
CREATE TABLE IF NOT EXISTS repositorio_documentos_versiones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_id BIGINT NOT NULL,
    numero_version INT NOT NULL,
    hash_sha256 VARCHAR(64) NOT NULL,
    ruta_almacenamiento VARCHAR(255) NOT NULL,
    nombre_archivo VARCHAR(255) NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    tamano_bytes BIGINT NOT NULL,
    motivo_version TEXT NOT NULL,
    usuario_autor_id BIGINT NOT NULL,
    fecha_registro TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_rep_doc_version UNIQUE (documento_id, numero_version),
    CONSTRAINT fk_rep_ver_documento FOREIGN KEY (documento_id) REFERENCES repositorio_documentos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_rep_ver_autor FOREIGN KEY (usuario_autor_id) REFERENCES usuarios (id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_rep_ver_doc ON repositorio_documentos_versiones (documento_id);

-- 4. Trámite de Solicitudes de Documentos en Línea (UC-05 A4, UC-11 A3, UC-PROV-27)
CREATE TABLE IF NOT EXISTS solicitudes_documentos_academicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_radicado VARCHAR(60) NOT NULL UNIQUE,
    estudiante_id BIGINT NOT NULL,
    solicitante_usuario_id BIGINT NOT NULL,
    rol_solicitante VARCHAR(30) NOT NULL,
    tipo_documento VARCHAR(50) NOT NULL,
    anio_lectivo_id BIGINT NOT NULL,
    motivo_solicitud TEXT NOT NULL,
    estado_solicitud VARCHAR(40) NOT NULL DEFAULT 'RADICADA',
    emision_generada_id BIGINT,
    fecha_radicacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_resolucion TIMESTAMP(6) WITHOUT TIME ZONE,
    observacion_secretaria TEXT,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_sol_doc_estudiante FOREIGN KEY (estudiante_id) REFERENCES estudiantes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sol_doc_solicitante FOREIGN KEY (solicitante_usuario_id) REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sol_doc_anio FOREIGN KEY (anio_lectivo_id) REFERENCES anios_lectivos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sol_doc_emision FOREIGN KEY (emision_generada_id) REFERENCES registro_emisiones_documentos (id) ON DELETE SET NULL,
    CONSTRAINT chk_sol_doc_estado CHECK (estado_solicitud IN (
        'RADICADA',
        'EN_TRAMITE',
        'GENERADA_DISPONIBLE',
        'RECHAZADA'
    ))
);

CREATE INDEX IF NOT EXISTS idx_sol_doc_est ON solicitudes_documentos_academicos (estudiante_id);
CREATE INDEX IF NOT EXISTS idx_sol_doc_estado ON solicitudes_documentos_academicos (estado_solicitud);

-- 5. Libros Reglamentarios Institucionales y Folios (UC-PROV-27, Decreto 1290 Art. 16)
CREATE TABLE IF NOT EXISTS libros_reglamentarios_folios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_lectivo_id BIGINT NOT NULL,
    tipo_libro VARCHAR(45) NOT NULL,
    numero_tomo INT NOT NULL DEFAULT 1,
    numero_folio INT NOT NULL,
    estudiante_id BIGINT,
    codigo_documento_asociado VARCHAR(60),
    resumen_registro_json TEXT NOT NULL,
    fecha_asiento DATE NOT NULL,
    secretario_usuario_id BIGINT NOT NULL,
    fecha_registro TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_libro_folio UNIQUE (anio_lectivo_id, tipo_libro, numero_tomo, numero_folio),
    CONSTRAINT fk_libro_folio_anio FOREIGN KEY (anio_lectivo_id) REFERENCES anios_lectivos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_libro_folio_estudiante FOREIGN KEY (estudiante_id) REFERENCES estudiantes (id) ON DELETE SET NULL,
    CONSTRAINT fk_libro_folio_secretario FOREIGN KEY (secretario_usuario_id) REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT chk_libro_tipo CHECK (tipo_libro IN (
        'LIBRO_MATRICULAS',
        'LIBRO_CALIFICACIONES_VALORACION',
        'LIBRO_ACTAS_GRADO',
        'LIBRO_VALIDACIONES'
    ))
);

CREATE INDEX IF NOT EXISTS idx_libro_folio_anio_tipo ON libros_reglamentarios_folios (anio_lectivo_id, tipo_libro);

-- 6. Alertas de Seguridad y Anomalías en Tiempo Real (UC-PROV-29 A2)
CREATE TABLE IF NOT EXISTS alertas_seguridad_auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_alerta VARCHAR(50) NOT NULL,
    severidad VARCHAR(25) NOT NULL DEFAULT 'ALTA',
    descripcion_evento TEXT NOT NULL,
    usuario_involucrado_id BIGINT,
    ip_origen VARCHAR(45),
    correlation_id VARCHAR(100),
    leida_por_rector BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_alerta TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_alerta_aud_usuario FOREIGN KEY (usuario_involucrado_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_alerta_aud_sev CHECK (severidad IN ('MEDIA', 'ALTA', 'CRITICA'))
);

CREATE INDEX IF NOT EXISTS idx_alerta_aud_tipo ON alertas_seguridad_auditoria (tipo_alerta);
CREATE INDEX IF NOT EXISTS idx_alerta_aud_fecha ON alertas_seguridad_auditoria (fecha_alerta);

