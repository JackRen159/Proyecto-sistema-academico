DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_emision_previa'
    ) THEN
        ALTER TABLE registro_emisiones_documentos
            ADD CONSTRAINT fk_emision_previa FOREIGN KEY (emision_previa_id) REFERENCES registro_emisiones_documentos (id) ON DELETE SET NULL;
