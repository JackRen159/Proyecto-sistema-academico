-- 7. Tabla de Auditoría Global Transversal Inmutable con Encadenamiento Criptográfico (UC-27, UC-PROV-29, RN-10, RN-DOC-06, RN-DOC-07)
CREATE TABLE IF NOT EXISTS auditoria_eventos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT,
    username VARCHAR(50) NOT NULL,
    rol_activo VARCHAR(30) NOT NULL,
    modulo VARCHAR(50) NOT NULL,
    accion VARCHAR(50) NOT NULL,
    entidad VARCHAR(50) NOT NULL,
    entidad_id VARCHAR(50),
    valor_anterior TEXT,
    valor_nuevo TEXT,
    motivo VARCHAR(255),
    resultado VARCHAR(20) NOT NULL DEFAULT 'EXITO',
    correlation_id VARCHAR(64) NOT NULL,
    direccion_ip VARCHAR(45),
    user_agent VARCHAR(255),
    fecha_evento TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    hash_anterior VARCHAR(64) NOT NULL,
    hash_evento VARCHAR(64) NOT NULL,
    CONSTRAINT fk_auditoria_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_auditoria_resultado CHECK (resultado IN ('EXITO', 'FALLO', 'DENEGADO'))
);

CREATE INDEX IF NOT EXISTS idx_auditoria_modulo_fecha ON auditoria_eventos (modulo, fecha_evento);
CREATE INDEX IF NOT EXISTS idx_auditoria_correlation ON auditoria_eventos (correlation_id);
CREATE INDEX IF NOT EXISTS idx_auditoria_usuario_fecha ON auditoria_eventos (usuario_id, fecha_evento);
CREATE INDEX IF NOT EXISTS idx_auditoria_entidad ON auditoria_eventos (entidad, entidad_id);
CREATE INDEX IF NOT EXISTS idx_auditoria_hash ON auditoria_eventos (hash_evento);

-- 8. Restricción Absoluta de Base de Datos: Trigger Append-Only contra UPDATE y DELETE (RN-DOC-07, E2)
CREATE OR REPLACE FUNCTION fn_prevenir_modificacion_auditoria()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'Operacion prohibida: la tabla auditoria_eventos es estrictamente append-only y no admite UPDATE ni DELETE (RN-DOC-07).';
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_auditoria_eventos_append_only ON auditoria_eventos;
CREATE TRIGGER trg_auditoria_eventos_append_only
BEFORE UPDATE OR DELETE ON auditoria_eventos
FOR EACH ROW
EXECUTE FUNCTION fn_prevenir_modificacion_auditoria();
