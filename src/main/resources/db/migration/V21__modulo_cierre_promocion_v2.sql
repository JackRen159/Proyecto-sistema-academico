-- 1. Observaciones Integrales de Dirección de Grupo para Boletines (UC-PROV-23)
CREATE TABLE IF NOT EXISTS observaciones_boletin_grupo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id BIGINT NOT NULL,
    periodo_academico_id BIGINT NOT NULL,
    docente_director_id BIGINT,
    observacion_formativa TEXT NOT NULL,
    recomendaciones_pedagogicas TEXT,
    version BIGINT NOT NULL DEFAULT 0,
    fecha_registro TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_obs_boletin_mat_periodo UNIQUE (matricula_id, periodo_academico_id),
    CONSTRAINT fk_obs_boletin_matricula FOREIGN KEY (matricula_id) REFERENCES matriculas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_obs_boletin_periodo FOREIGN KEY (periodo_academico_id) REFERENCES periodos_academicos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_obs_boletin_director FOREIGN KEY (docente_director_id) REFERENCES profesores (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_obs_boletin_mat ON observaciones_boletin_grupo (matricula_id);
CREATE INDEX IF NOT EXISTS idx_obs_boletin_per ON observaciones_boletin_grupo (periodo_academico_id);

-- 2. Snapshots Inmutables de Boletines Publicados y Versionados (UC-20, RN-CIE-04)
CREATE TABLE IF NOT EXISTS boletines_publicados_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id BIGINT NOT NULL,
    periodo_academico_id BIGINT NOT NULL,
    numero_version INT NOT NULL DEFAULT 1,
    estado_boletin VARCHAR(35) NOT NULL DEFAULT 'PUBLICADO_OFICIAL',
    datos_json TEXT NOT NULL,
    usuario_publicador_id BIGINT,
    fecha_publicacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_reapertura TIMESTAMP(6) WITHOUT TIME ZONE,
    motivo_reapertura TEXT,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_boletin_mat_per_version UNIQUE (matricula_id, periodo_academico_id, numero_version),
    CONSTRAINT fk_boletin_ver_matricula FOREIGN KEY (matricula_id) REFERENCES matriculas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_boletin_ver_periodo FOREIGN KEY (periodo_academico_id) REFERENCES periodos_academicos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_boletin_ver_usuario FOREIGN KEY (usuario_publicador_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_boletin_ver_estado CHECK (estado_boletin IN (
        'PUBLICADO_OFICIAL',
        'APLAZADO_POR_EXCUSA_JUSTIFICADA',
        'RECTIFICADO_HISTORICO'
    ))
);

CREATE INDEX IF NOT EXISTS idx_boletin_ver_mat ON boletines_publicados_version (matricula_id);
CREATE INDEX IF NOT EXISTS idx_boletin_ver_per ON boletines_publicados_version (periodo_academico_id);
CREATE INDEX IF NOT EXISTS idx_boletin_ver_estado ON boletines_publicados_version (estado_boletin);

-- 3. Actas Periódicas de Comisión de Evaluación y Promoción (UC-PROV-23)
CREATE TABLE IF NOT EXISTS actas_comision_evaluacion_periodica (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    periodo_academico_id BIGINT NOT NULL,
    grado_id BIGINT NOT NULL,
    numero_acta VARCHAR(50) NOT NULL,
    fecha_sesion DATE NOT NULL,
    integrantes_nominativos_json TEXT NOT NULL,
    conclusiones_generales TEXT,
    compromisos_pedagogicos_json TEXT,
    usuario_secretario_id BIGINT,
    fecha_registro TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_acta_comision_numero UNIQUE (numero_acta),
    CONSTRAINT fk_acta_com_periodo FOREIGN KEY (periodo_academico_id) REFERENCES periodos_academicos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_acta_com_grado FOREIGN KEY (grado_id) REFERENCES grados (id) ON DELETE RESTRICT,
    CONSTRAINT fk_acta_com_usuario FOREIGN KEY (usuario_secretario_id) REFERENCES usuarios (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_acta_com_per ON actas_comision_evaluacion_periodica (periodo_academico_id);
CREATE INDEX IF NOT EXISTS idx_acta_com_grado ON actas_comision_evaluacion_periodica (grado_id);

-- 4. Actas Colegiadas de Promoción Anual (UC-21, RN-CIE-06)
CREATE TABLE IF NOT EXISTS actas_promocion_anual (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_lectivo_id BIGINT NOT NULL,
    grado_id BIGINT NOT NULL,
    grupo_id BIGINT,
    numero_acta VARCHAR(50) NOT NULL,
    tipo_acta VARCHAR(40) NOT NULL DEFAULT 'ORDINARIA_COMISION',
    fecha_acta DATE NOT NULL,
    integrantes_nominativos_json TEXT NOT NULL,
    soporte_acta_url VARCHAR(255),
    observaciones TEXT,
    usuario_registro_id BIGINT,
    fecha_registro TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_acta_promocion_numero UNIQUE (numero_acta),
    CONSTRAINT fk_acta_prom_anio FOREIGN KEY (anio_lectivo_id) REFERENCES anios_lectivos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_acta_prom_grado FOREIGN KEY (grado_id) REFERENCES grados (id) ON DELETE RESTRICT,
    CONSTRAINT fk_acta_prom_grupo FOREIGN KEY (grupo_id) REFERENCES grupos (id) ON DELETE SET NULL,
    CONSTRAINT fk_acta_prom_usuario FOREIGN KEY (usuario_registro_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_acta_prom_tipo CHECK (tipo_acta IN (
        'ORDINARIA_COMISION',
        'HABILITACION_FINAL',
        'RECTIFICATORIA',
        'CONSEJO_DIRECTIVO_ANTICIPADA'
    ))
);

CREATE INDEX IF NOT EXISTS idx_acta_prom_anio ON actas_promocion_anual (anio_lectivo_id);
CREATE INDEX IF NOT EXISTS idx_acta_prom_grado ON actas_promocion_anual (grado_id);

-- 5. Decisiones de Promoción Anual por Estudiante (UC-21, RN-CIE-05, RN-CIE-07, RN-CIE-08)
CREATE TABLE IF NOT EXISTS promocion_estudiantes_anual (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acta_promocion_id BIGINT NOT NULL,
    matricula_id BIGINT NOT NULL,
    estado_promocion VARCHAR(40) NOT NULL,
    promedio_general NUMERIC(4,2) NOT NULL,
    areas_reprobadas INT NOT NULL DEFAULT 0,
    asignaturas_reprobadas INT NOT NULL DEFAULT 0,
    porcentaje_inasistencia_anual NUMERIC(5,2) NOT NULL DEFAULT 0.00,
    grado_destino_id BIGINT,
    motivo_decision TEXT,
    version BIGINT NOT NULL DEFAULT 0,
    fecha_registro TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_promocion_estudiante_matricula UNIQUE (matricula_id),
    CONSTRAINT fk_prom_est_acta FOREIGN KEY (acta_promocion_id) REFERENCES actas_promocion_anual (id) ON DELETE RESTRICT,
    CONSTRAINT fk_prom_est_matricula FOREIGN KEY (matricula_id) REFERENCES matriculas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_prom_est_grado_destino FOREIGN KEY (grado_destino_id) REFERENCES grados (id) ON DELETE RESTRICT,
    CONSTRAINT chk_prom_est_estado CHECK (estado_promocion IN (
        'PROMOVIDO_DIRECTO',
        'PROMOVIDO_PREESCOLAR',
        'PENDIENTE_RECUPERACION_FINAL',
        'PROMOVIDO_POR_RECUPERACION_FINAL',
        'NO_PROMOVIDO_REPROBADO',
        'PROMOCION_ANTICIPADA_APROBADA'
    ))
);

CREATE INDEX IF NOT EXISTS idx_prom_est_mat ON promocion_estudiantes_anual (matricula_id);
CREATE INDEX IF NOT EXISTS idx_prom_est_estado ON promocion_estudiantes_anual (estado_promocion);
CREATE INDEX IF NOT EXISTS idx_prom_est_acta ON promocion_estudiantes_anual (acta_promocion_id);

-- 6. Titulación de Graduandos de Educación Media (UC-PROV-24, RN-CIE-09, BRE-021)
CREATE TABLE IF NOT EXISTS titulacion_graduandos_media (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id BIGINT NOT NULL,
    modalidad_titulo VARCHAR(50) NOT NULL DEFAULT 'BACHILLER_ACADEMICO',
    especialidad VARCHAR(100),
    horas_servicio_social INT NOT NULL DEFAULT 0,
    soporte_servicio_social_url VARCHAR(255),
    codigo_registro_icfes VARCHAR(50),
    documento_identidad_verificado BOOLEAN NOT NULL DEFAULT TRUE,
    estado_titulacion VARCHAR(35) NOT NULL DEFAULT 'APTO_GRADUACION',
    numero_acta_general VARCHAR(50),
    numero_acta_individual VARCHAR(50),
    numero_diploma VARCHAR(50),
    numero_libro VARCHAR(20),
    numero_folio VARCHAR(20),
    fecha_graduacion DATE,
    usuario_autorizador_id BIGINT,
    version BIGINT NOT NULL DEFAULT 0,
    fecha_registro TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_titulacion_matricula UNIQUE (matricula_id),
    CONSTRAINT fk_titulacion_matricula FOREIGN KEY (matricula_id) REFERENCES matriculas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_titulacion_usuario FOREIGN KEY (usuario_autorizador_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_titulacion_modalidad CHECK (modalidad_titulo IN ('BACHILLER_ACADEMICO', 'BACHILLER_TECNICO')),
    CONSTRAINT chk_titulacion_estado CHECK (estado_titulacion IN (
        'APTO_GRADUACION',
        'GRADUADO_EGRESADO',
        'APROBADO_PENDIENTE_TITULACION'
    ))
);

CREATE INDEX IF NOT EXISTS idx_titulacion_mat ON titulacion_graduandos_media (matricula_id);
CREATE INDEX IF NOT EXISTS idx_titulacion_estado ON titulacion_graduandos_media (estado_titulacion);
CREATE INDEX IF NOT EXISTS idx_titulacion_fecha ON titulacion_graduandos_media (fecha_graduacion);
