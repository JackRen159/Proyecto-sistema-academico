-- 1. Casos de Convivencia y Ruta de Atención Integral (UC-23, RN-06, RN-CON-04..06)
CREATE TABLE IF NOT EXISTS casos_convivencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_expediente VARCHAR(60) NOT NULL UNIQUE,
    anio_lectivo_id BIGINT NOT NULL,
    estudiante_implicado_id BIGINT NOT NULL,
    tipo_situacion VARCHAR(30) NOT NULL,
    estado_caso VARCHAR(65) NOT NULL DEFAULT 'ABIERTO_PRELIMINAR_URGENTE',
    fecha_hechos DATE NOT NULL,
    lugar_hechos VARCHAR(150) NOT NULL,
    descripcion_situacion TEXT NOT NULL,
    reportante_usuario_id BIGINT,
    es_reporte_confidencial BOOLEAN NOT NULL DEFAULT FALSE,
    atencion_medica_urgente BOOLEAN NOT NULL DEFAULT FALSE,
    detalle_atencion_medica TEXT,
    reserva_proteccion_contra_acudiente BOOLEAN NOT NULL DEFAULT FALSE,
    acudiente_agresor_id BIGINT,
    codigo_siuce VARCHAR(80),
    remitido_autoridad_externa BOOLEAN NOT NULL DEFAULT FALSE,
    autoridad_externa_detalle TEXT,
    fecha_remision_externa DATE,
    radicado_remision_externa VARCHAR(100),
    fecha_apertura TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_cierre TIMESTAMP(6) WITHOUT TIME ZONE,
    motivo_cierre TEXT,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_caso_conv_anio FOREIGN KEY (anio_lectivo_id) REFERENCES anios_lectivos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_caso_conv_estudiante FOREIGN KEY (estudiante_implicado_id) REFERENCES estudiantes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_caso_conv_reportante FOREIGN KEY (reportante_usuario_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT fk_caso_conv_acudiente_agresor FOREIGN KEY (acudiente_agresor_id) REFERENCES acudientes (id) ON DELETE SET NULL,
    CONSTRAINT chk_caso_conv_tipo CHECK (tipo_situacion IN (
        'TIPO_I',
        'TIPO_II',
        'TIPO_III',
        'FALTA_DISCIPLINARIA'
    )),
    CONSTRAINT chk_caso_conv_estado CHECK (estado_caso IN (
        'ABIERTO_PRELIMINAR_URGENTE',
        'EN_PROTOCOLO_ATENCION',
        'EN_DEBIDO_PROCESO',
        'EN_SEGUIMIENTO_COMITE',
        'CERRADO_SUPERADO',
        'SEGUIMIENTO_INTERNO_CUMPLIDO_EN_MANOS_AUTORIDAD_EXTERNA'
    ))
);

CREATE INDEX IF NOT EXISTS idx_caso_conv_anio ON casos_convivencia (anio_lectivo_id);
CREATE INDEX IF NOT EXISTS idx_caso_conv_est ON casos_convivencia (estudiante_implicado_id);
CREATE INDEX IF NOT EXISTS idx_caso_conv_tipo ON casos_convivencia (tipo_situacion);
CREATE INDEX IF NOT EXISTS idx_caso_conv_estado ON casos_convivencia (estado_caso);

-- 2. Observador del Estudiante (UC-22, RN-CON-01, RN-CON-02, RN-CON-03)
CREATE TABLE IF NOT EXISTS anotaciones_observador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL,
    periodo_academico_id BIGINT,
    autor_usuario_id BIGINT NOT NULL,
    tipo_anotacion VARCHAR(45) NOT NULL,
    fecha_hecho DATE NOT NULL,
    hora_hecho TIME,
    lugar_hecho VARCHAR(150) NOT NULL,
    descripcion_factica TEXT NOT NULL,
    acciones_pedagogicas TEXT,
    es_zona_comun BOOLEAN NOT NULL DEFAULT FALSE,
    requiere_activacion_ruta BOOLEAN NOT NULL DEFAULT FALSE,
    caso_convivencia_id BIGINT,
    version_libre_estudiante TEXT,
    fecha_version_estudiante TIMESTAMP(6) WITHOUT TIME ZONE,
    enterado_acudiente BOOLEAN NOT NULL DEFAULT FALSE,
    acudiente_usuario_id BIGINT,
    fecha_enterado_acudiente TIMESTAMP(6) WITHOUT TIME ZONE,
    anotacion_firmada BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_registro TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_obs_estudiante FOREIGN KEY (estudiante_id) REFERENCES estudiantes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_obs_periodo FOREIGN KEY (periodo_academico_id) REFERENCES periodos_academicos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_obs_autor FOREIGN KEY (autor_usuario_id) REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT fk_obs_caso FOREIGN KEY (caso_convivencia_id) REFERENCES casos_convivencia (id) ON DELETE SET NULL,
    CONSTRAINT fk_obs_acudiente FOREIGN KEY (acudiente_usuario_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_obs_tipo CHECK (tipo_anotacion IN (
        'POSITIVA_RECONOCIMIENTO',
        'SEGUIMIENTO_FORMATIVO',
        'REPORTE_SITUACION_CONVIVENCIA'
    ))
);

CREATE INDEX IF NOT EXISTS idx_obs_estudiante ON anotaciones_observador (estudiante_id);
CREATE INDEX IF NOT EXISTS idx_obs_periodo ON anotaciones_observador (periodo_academico_id);
CREATE INDEX IF NOT EXISTS idx_obs_autor ON anotaciones_observador (autor_usuario_id);
CREATE INDEX IF NOT EXISTS idx_obs_tipo ON anotaciones_observador (tipo_anotacion);

-- 3. Adendas Inmutables de Anotaciones del Observador (UC-22 A3, RN-CON-01, E4)
CREATE TABLE IF NOT EXISTS anotaciones_observador_adendas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anotacion_id BIGINT NOT NULL,
    autor_usuario_id BIGINT NOT NULL,
    motivo_adenda TEXT NOT NULL,
    contenido_adenda TEXT NOT NULL,
    fecha_adenda TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_adenda_anotacion FOREIGN KEY (anotacion_id) REFERENCES anotaciones_observador (id) ON DELETE RESTRICT,
    CONSTRAINT fk_adenda_autor FOREIGN KEY (autor_usuario_id) REFERENCES usuarios (id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_adenda_anotacion ON anotaciones_observador_adendas (anotacion_id);

-- 4. Actuaciones de la Ruta de Atención Integral (UC-23, RN-CON-05)
CREATE TABLE IF NOT EXISTS actuaciones_ruta_atencion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caso_convivencia_id BIGINT NOT NULL,
    tipo_actuacion VARCHAR(50) NOT NULL,
    descripcion_actuacion TEXT NOT NULL,
    responsable_usuario_id BIGINT NOT NULL,
    fecha_actuacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_vencimiento_seguimiento DATE,
    compromisos_acordados TEXT,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_actuacion_caso FOREIGN KEY (caso_convivencia_id) REFERENCES casos_convivencia (id) ON DELETE RESTRICT,
    CONSTRAINT fk_actuacion_responsable FOREIGN KEY (responsable_usuario_id) REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT chk_actuacion_tipo CHECK (tipo_actuacion IN (
        'ATENCION_SALUD',
        'MEDIACION_CONCILIACION',
        'MEDIDA_PROTECCION',
        'COMUNICACION_ACUDIENTE',
        'REMISION_EXTERNA',
        'SEGUIMIENTO_ORIENTACION'
    ))
);

CREATE INDEX IF NOT EXISTS idx_actuacion_caso ON actuaciones_ruta_atencion (caso_convivencia_id);

-- 5. Expedientes de Debido Proceso Disciplinario (UC-PROV-25, RN-07, RN-CON-07)
CREATE TABLE IF NOT EXISTS expedientes_debido_proceso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_expediente VARCHAR(60) NOT NULL UNIQUE,
    caso_convivencia_id BIGINT NOT NULL,
    estudiante_id BIGINT NOT NULL,
    estado_expediente VARCHAR(65) NOT NULL DEFAULT 'APERTURA_NOTIFICADA',
    instructor_usuario_id BIGINT NOT NULL,
    auto_apertura_hechos TEXT NOT NULL,
    normas_manual_infringidas TEXT NOT NULL,
    pruebas_trasladadas_anonimizadas TEXT NOT NULL,
    fecha_notificacion_cargos TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    dias_habiles_descargos INT NOT NULL DEFAULT 5,
    fecha_limite_descargos DATE NOT NULL,
    constancia_vencimiento_descargos TEXT,
    acompanamiento_personero BOOLEAN NOT NULL DEFAULT FALSE,
    concepto_orientacion TEXT,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_exp_deb_caso FOREIGN KEY (caso_convivencia_id) REFERENCES casos_convivencia (id) ON DELETE RESTRICT,
    CONSTRAINT fk_exp_deb_estudiante FOREIGN KEY (estudiante_id) REFERENCES estudiantes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_exp_deb_instructor FOREIGN KEY (instructor_usuario_id) REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT chk_exp_deb_estado CHECK (estado_expediente IN (
        'APERTURA_NOTIFICADA',
        'CARGOS_NOTIFICADOS_EN_TERMINO_DESCARGOS',
        'DESCARGOS_RECIBIDOS_LISTO_PARA_DECISION',
        'PLAZO_DESCARGOS_VENCIDO_CERTIFICADO',
        'FALLO_PRIMERA_INSTANCIA_EMITIDO',
        'EN_RECURSO_EFECTO_SUSPENSIVO',
        'FALLO_SEGUNDA_INSTANCIA_EMITIDO',
        'CERRADO_EN_FIRME',
        'ARCHIVADO_REVOCADO'
    ))
);

CREATE INDEX IF NOT EXISTS idx_exp_deb_caso ON expedientes_debido_proceso (caso_convivencia_id);
CREATE INDEX IF NOT EXISTS idx_exp_deb_estudiante ON expedientes_debido_proceso (estudiante_id);
CREATE INDEX IF NOT EXISTS idx_exp_deb_estado ON expedientes_debido_proceso (estado_expediente);

-- 6. Descargos y Contradicción Probatoria del Debido Proceso (UC-PROV-25)
CREATE TABLE IF NOT EXISTS descargos_debido_proceso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expediente_id BIGINT NOT NULL,
    presentado_por_usuario_id BIGINT NOT NULL,
    contenido_descargos TEXT NOT NULL,
    pruebas_aportadas TEXT,
    fecha_radicacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    es_version_libre_audiencia BOOLEAN NOT NULL DEFAULT FALSE,
    participo_personero BOOLEAN NOT NULL DEFAULT FALSE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_descargo_expediente FOREIGN KEY (expediente_id) REFERENCES expedientes_debido_proceso (id) ON DELETE RESTRICT,
    CONSTRAINT fk_descargo_usuario FOREIGN KEY (presentado_por_usuario_id) REFERENCES usuarios (id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_descargo_expediente ON descargos_debido_proceso (expediente_id);

-- 7. Medidas Pedagógicas y Sanciones Disciplinarias (UC-24, RN-07, RN-08)
CREATE TABLE IF NOT EXISTS medidas_sanciones_convivencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expediente_id BIGINT NOT NULL,
    numero_resolucion VARCHAR(60) NOT NULL UNIQUE,
    tipo_medida VARCHAR(50) NOT NULL,
    es_sancion_disciplinaria BOOLEAN NOT NULL DEFAULT FALSE,
    motivacion_hechos_normas TEXT NOT NULL,
    analisis_proporcionalidad TEXT NOT NULL,
    dias_suspension INT,
    fecha_inicio_suspension DATE,
    fecha_fin_suspension DATE,
    acta_consejo_directivo VARCHAR(80),
    fecha_acta_consejo_directivo DATE,
    autoridad_firmante_id BIGINT NOT NULL,
    rol_firmante VARCHAR(40) NOT NULL,
    estado_decision VARCHAR(45) NOT NULL DEFAULT 'EMITIDA_PENDIENTE_NOTIFICACION',
    fecha_emision TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_notificacion TIMESTAMP(6) WITHOUT TIME ZONE,
    fecha_firmeza TIMESTAMP(6) WITHOUT TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_medida_expediente FOREIGN KEY (expediente_id) REFERENCES expedientes_debido_proceso (id) ON DELETE RESTRICT,
    CONSTRAINT fk_medida_firmante FOREIGN KEY (autoridad_firmante_id) REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT chk_medida_tipo CHECK (tipo_medida IN (
        'COMPROMISO_PEDAGOGICO',
        'AMONESTACION_ESCRITA',
        'ACCION_RESTAURATIVA_COMUNITARIA',
        'SUSPENSION_TEMPORAL_ASISTENCIA',
        'CANCELACION_MATRICULA_EXPULSION',
        'PERDIDA_CUPO_SIGUIENTE_ANIO'
    )),
    CONSTRAINT chk_medida_estado CHECK (estado_decision IN (
        'EMITIDA_PENDIENTE_NOTIFICACION',
        'NOTIFICADA_EN_TERMINO_RECURSOS',
        'EN_RECURSO_EFECTO_SUSPENSIVO',
        'EN_FIRME',
        'REVOCADA_POR_RECURSO'
    ))
);

CREATE INDEX IF NOT EXISTS idx_medida_expediente ON medidas_sanciones_convivencia (expediente_id);
CREATE INDEX IF NOT EXISTS idx_medida_estado ON medidas_sanciones_convivencia (estado_decision);

-- 8. Plan de Continuidad Académica Obligatorio en Suspensiones (UC-24 A1, RN-08, Sentencia T-004 de 2026)
CREATE TABLE IF NOT EXISTS planes_continuidad_academica (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medida_sancion_id BIGINT NOT NULL UNIQUE,
    estudiante_id BIGINT NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    guias_talleres_descripcion TEXT NOT NULL,
    mecanismo_evaluacion TEXT NOT NULL,
    docente_tutor_seguimiento_id BIGINT,
    cumplido_satisfactoriamente BOOLEAN NOT NULL DEFAULT FALSE,
    observaciones_evaluacion TEXT,
    fecha_registro TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_plan_cont_medida FOREIGN KEY (medida_sancion_id) REFERENCES medidas_sanciones_convivencia (id) ON DELETE RESTRICT,
    CONSTRAINT fk_plan_cont_estudiante FOREIGN KEY (estudiante_id) REFERENCES estudiantes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_plan_cont_tutor FOREIGN KEY (docente_tutor_seguimiento_id) REFERENCES profesores (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_plan_cont_medida ON planes_continuidad_academica (medida_sancion_id);
CREATE INDEX IF NOT EXISTS idx_plan_cont_estudiante ON planes_continuidad_academica (estudiante_id);

-- 9. Recursos de Reposición y Apelación con Efecto Suspensivo (UC-PROV-25, RN-CON-08)
CREATE TABLE IF NOT EXISTS recursos_impugnacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medida_sancion_id BIGINT NOT NULL,
    tipo_recurso VARCHAR(45) NOT NULL,
    recurrente_usuario_id BIGINT NOT NULL,
    sustentacion_recurso TEXT NOT NULL,
    pruebas_adjuntas TEXT,
    fecha_radicacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    estado_recurso VARCHAR(45) NOT NULL DEFAULT 'RADICADO_EN_TRAMITE',
    resolutor_usuario_id BIGINT,
    resolutor_rol VARCHAR(40),
    acta_consejo_directivo_resolucion VARCHAR(80),
    motivo_resolucion_recurso TEXT,
    fecha_resolucion TIMESTAMP(6) WITHOUT TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_recurso_medida FOREIGN KEY (medida_sancion_id) REFERENCES medidas_sanciones_convivencia (id) ON DELETE RESTRICT,
    CONSTRAINT fk_recurso_recurrente FOREIGN KEY (recurrente_usuario_id) REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT fk_recurso_resolutor FOREIGN KEY (resolutor_usuario_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_recurso_tipo CHECK (tipo_recurso IN (
        'REPOSICION',
        'APELACION',
        'REPOSICION_Y_EN_SUBSIDIO_APELACION'
    )),
    CONSTRAINT chk_recurso_estado CHECK (estado_recurso IN (
        'RADICADO_EN_TRAMITE',
        'RESUELTO_CONFIRMADA_MEDIDA',
        'RESUELTO_MODIFICADA_MEDIDA',
        'RESUELTO_REVOCADA_MEDIDA'
    ))
);

CREATE INDEX IF NOT EXISTS idx_recurso_medida ON recursos_impugnacion (medida_sancion_id);
CREATE INDEX IF NOT EXISTS idx_recurso_estado ON recursos_impugnacion (estado_recurso);

