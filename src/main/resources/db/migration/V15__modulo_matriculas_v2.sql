-- 1. Ampliación de la tabla `matriculas` con campos normativos de formalización y permanencia
ALTER TABLE matriculas
    ADD COLUMN IF NOT EXISTS fecha_efectiva_inicio DATE,
    ADD COLUMN IF NOT EXISTS fecha_efectiva_retiro DATE,
    ADD COLUMN IF NOT EXISTS institucion_procedencia VARCHAR(150),
    ADD COLUMN IF NOT EXISTS acudiente_principal_id BIGINT,
    ADD COLUMN IF NOT EXISTS siee_version_id BIGINT,
    ADD COLUMN IF NOT EXISTS manual_convivencia_version_id BIGINT,
    ADD COLUMN IF NOT EXISTS fecha_aceptacion_reglamentos TIMESTAMP(6) WITHOUT TIME ZONE,
    ADD COLUMN IF NOT EXISTS acta_consejo_directivo VARCHAR(50),
    ADD COLUMN IF NOT EXISTS fecha_acta_consejo_directivo DATE,
    ADD COLUMN IF NOT EXISTS consentimiento_acudiente BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS es_repitente BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_matriculas_acudiente_principal') THEN
        ALTER TABLE matriculas
            ADD CONSTRAINT fk_matriculas_acudiente_principal
            FOREIGN KEY (acudiente_principal_id) REFERENCES acudientes (id) ON DELETE RESTRICT;
    END IF;

    -- Ajustar la restricción de estados para admitir el ciclo de vida V2
    ALTER TABLE matriculas DROP CONSTRAINT IF EXISTS chk_matriculas_estado;
    ALTER TABLE matriculas
        ADD CONSTRAINT chk_matriculas_estado
        CHECK (estado IN ('INSCRITA', 'EN_PROCESO', 'PENDIENTE_DOCUMENTOS', 'MATRICULADA', 'MATRICULADO_ACTIVO',
                          'RETIRADA', 'RETIRADO_VOLUNTARIO', 'TRASLADADO_SALIENTE', 'RETIRADO_DESERCION',
                          'CANCELADA_EXPULSION', 'ANULADA_ADMINISTRATIVAMENTE', 'FINALIZADA'));

    -- Ajustar la restricción de tipos / modalidades de matrícula
    ALTER TABLE matriculas DROP CONSTRAINT IF EXISTS chk_matriculas_tipo;
    ALTER TABLE matriculas
        ADD CONSTRAINT chk_matriculas_tipo
        CHECK (tipo_matricula IN ('REGULAR', 'NUEVO', 'NUEVO_INGRESO', 'RENOVACION_ANTIGUO',
                                  'REINCORPORADO', 'TRASLADO_EXTERNO', 'TRASLADO_ENTRANTE', 'REPITENCIA'));
END $$;

-- Actualizar fecha efectiva de inicio por defecto para matrículas históricas ya existentes
UPDATE matriculas SET fecha_efectiva_inicio = fecha_matricula WHERE fecha_efectiva_inicio IS NULL;

-- Actualizar índice único de matrícula activa/en proceso por estudiante y año lectivo (RN-MAT-01)
DROP INDEX IF EXISTS uk_matriculas_estudiante_anio_activo;
CREATE UNIQUE INDEX IF NOT EXISTS uk_matriculas_estudiante_anio_activo
    ON matriculas (estudiante_id, anio_lectivo_id)
    WHERE estado IN ('MATRICULADA', 'MATRICULADO_ACTIVO', 'EN_PROCESO', 'PENDIENTE_DOCUMENTOS');

CREATE INDEX IF NOT EXISTS idx_matriculas_acudiente ON matriculas (acudiente_principal_id);
CREATE INDEX IF NOT EXISTS idx_matriculas_fecha_efectiva ON matriculas (fecha_efectiva_inicio, fecha_efectiva_retiro);

-- 2. Tabla unificada de Novedades de Matrícula (UC-PROV-09, RN-MAT-06, RN-MAT-07, RN-MAT-08)
CREATE TABLE IF NOT EXISTS historial_novedades_matricula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id BIGINT NOT NULL,
    tipo_novedad VARCHAR(35) NOT NULL,
    grupo_origen_id BIGINT,
    grupo_destino_id BIGINT,
    grado_origen_id BIGINT,
    grado_destino_id BIGINT,
    fecha_efectiva DATE NOT NULL DEFAULT CURRENT_DATE,
    motivo VARCHAR(500) NOT NULL,
    soporte_documento VARCHAR(255),
    numero_acta_resolucion VARCHAR(100),
    fecha_acta_resolucion DATE,
    solicitante VARCHAR(100),
    usuario_id BIGINT,
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_novedades_matricula FOREIGN KEY (matricula_id) REFERENCES matriculas (id) ON DELETE CASCADE,
    CONSTRAINT fk_novedades_grupo_origen FOREIGN KEY (grupo_origen_id) REFERENCES grupos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_novedades_grupo_destino FOREIGN KEY (grupo_destino_id) REFERENCES grupos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_novedades_grado_origen FOREIGN KEY (grado_origen_id) REFERENCES grados (id) ON DELETE RESTRICT,
    CONSTRAINT fk_novedades_grado_destino FOREIGN KEY (grado_destino_id) REFERENCES grados (id) ON DELETE RESTRICT,
    CONSTRAINT fk_novedades_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_novedades_tipo CHECK (tipo_novedad IN ('CAMBIO_GRUPO', 'PROMOCION_ANTICIPADA',
                                                         'RETIRO_VOLUNTARIO', 'TRASLADO_SALIENTE',
                                                         'DESERCION', 'CANCELACION_EXPULSION',
                                                         'ANULADA_ADMINISTRATIVAMENTE', 'OTRO'))
);

CREATE INDEX IF NOT EXISTS idx_novedades_matricula ON historial_novedades_matricula (matricula_id);
CREATE INDEX IF NOT EXISTS idx_novedades_tipo ON historial_novedades_matricula (tipo_novedad);
CREATE INDEX IF NOT EXISTS idx_novedades_fecha ON historial_novedades_matricula (fecha_efectiva);

-- Migrar datos preexistentes de traslados a la nueva tabla unificada de novedades
INSERT INTO historial_novedades_matricula (matricula_id, tipo_novedad, grupo_origen_id, grupo_destino_id, motivo, usuario_id, fecha_efectiva, fecha_creacion)
SELECT matricula_id, 'CAMBIO_GRUPO', grupo_origen_id, grupo_destino_id, motivo, usuario_id, fecha_traslado::DATE, fecha_traslado
FROM historial_traslados_matricula
ON CONFLICT DO NOTHING;
