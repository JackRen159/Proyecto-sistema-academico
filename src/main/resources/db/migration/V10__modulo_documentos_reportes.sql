-- 1. Tabla de Configuración de Consecutivos / Foliados por Año Lectivo
CREATE TABLE IF NOT EXISTS consecutivos_documentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_lectivo_id BIGINT NOT NULL,
    tipo_documento VARCHAR(50) NOT NULL,
    prefijo VARCHAR(20) NOT NULL DEFAULT '',
    ultimo_numero BIGINT NOT NULL DEFAULT 0,
    longitud_relleno INT NOT NULL DEFAULT 5,
    texto_pie_pagina VARCHAR(500),
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_consecutivo_anio_tipo UNIQUE (anio_lectivo_id, tipo_documento),
    CONSTRAINT fk_consecutivo_anio FOREIGN KEY (anio_lectivo_id) REFERENCES anios_lectivos (id) ON DELETE RESTRICT,
    CONSTRAINT chk_consecutivo_ultimo_numero CHECK (ultimo_numero >= 0),
    CONSTRAINT chk_consecutivo_longitud CHECK (longitud_relleno >= 1 AND longitud_relleno <= 10)
);

CREATE INDEX IF NOT EXISTS idx_consecutivos_anio ON consecutivos_documentos (anio_lectivo_id);

-- 2. Tabla de Registro y Auditoría de Emisiones de Documentos Oficiales
CREATE TABLE IF NOT EXISTS registro_emisiones_documentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consecutivo_id BIGINT,
    tipo_documento VARCHAR(50) NOT NULL,
    numero_consecutivo_completo VARCHAR(100) NOT NULL,
    anio_lectivo_id BIGINT NOT NULL,
    estudiante_id BIGINT,
    matricula_id BIGINT,
    periodo_academico_id BIGINT,
    grupo_id BIGINT,
    codigo_verificacion VARCHAR(64) NOT NULL,
    usuario_emisor_id BIGINT,
    destinatario VARCHAR(200),
    motivo VARCHAR(255),
    metadatos_json TEXT,
    anulado BOOLEAN NOT NULL DEFAULT FALSE,
    motivo_anulacion VARCHAR(255),
    fecha_anulacion TIMESTAMP(6) WITHOUT TIME ZONE,
    usuario_anulador_id BIGINT,
    fecha_emision TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_emision_consecutivo FOREIGN KEY (consecutivo_id) REFERENCES consecutivos_documentos (id) ON DELETE SET NULL,
    CONSTRAINT fk_emision_anio FOREIGN KEY (anio_lectivo_id) REFERENCES anios_lectivos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_emision_estudiante FOREIGN KEY (estudiante_id) REFERENCES estudiantes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_emision_matricula FOREIGN KEY (matricula_id) REFERENCES matriculas (id) ON DELETE RESTRICT,
    CONSTRAINT fk_emision_periodo FOREIGN KEY (periodo_academico_id) REFERENCES periodos_academicos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_emision_grupo FOREIGN KEY (grupo_id) REFERENCES grupos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_emision_usuario_emisor FOREIGN KEY (usuario_emisor_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT fk_emision_usuario_anulador FOREIGN KEY (usuario_anulador_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT uk_emision_codigo_verificacion UNIQUE (codigo_verificacion),
    CONSTRAINT uk_emision_consecutivo UNIQUE (anio_lectivo_id, tipo_documento, numero_consecutivo_completo)
);

CREATE INDEX IF NOT EXISTS idx_emisiones_estudiante ON registro_emisiones_documentos (estudiante_id);
CREATE INDEX IF NOT EXISTS idx_emisiones_matricula ON registro_emisiones_documentos (matricula_id);
CREATE INDEX IF NOT EXISTS idx_emisiones_anio_tipo ON registro_emisiones_documentos (anio_lectivo_id, tipo_documento);
CREATE INDEX IF NOT EXISTS idx_emisiones_codigo_verif ON registro_emisiones_documentos (codigo_verificacion);
