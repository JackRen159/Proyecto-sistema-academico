-- 1. Tabla de Profesores / Docentes
CREATE TABLE IF NOT EXISTS profesores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT,
    documento VARCHAR(20) NOT NULL,
    tipo_documento VARCHAR(10) NOT NULL DEFAULT 'CC',
    nombres VARCHAR(50) NOT NULL,
    apellidos VARCHAR(50) NOT NULL,
    correo VARCHAR(100) NOT NULL,
    telefono VARCHAR(20),
    direccion VARCHAR(150),
    titulo_academico VARCHAR(100),
    especialidad VARCHAR(100),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_profesores_documento UNIQUE (documento),
    CONSTRAINT uk_profesores_correo UNIQUE (correo),
    CONSTRAINT uk_profesores_usuario UNIQUE (usuario_id),
    CONSTRAINT fk_profesores_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT chk_profesores_tipo_doc CHECK (tipo_documento IN ('CC', 'CE', 'PASAPORTE', 'PEP', 'PPT'))
);

CREATE INDEX IF NOT EXISTS idx_profesores_usuario ON profesores (usuario_id);
CREATE INDEX IF NOT EXISTS idx_profesores_activo ON profesores (activo);

-- 2. Tabla de Asignaciones Académicas (Docente - Grupo - Asignatura por Vigencia)
CREATE TABLE IF NOT EXISTS asignaciones_academicas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profesor_id BIGINT NOT NULL,
    grupo_id BIGINT NOT NULL,
    asignatura_id BIGINT NOT NULL,
    intensidad_horaria_semanal INT NOT NULL DEFAULT 1,
    es_director_grupo BOOLEAN NOT NULL DEFAULT FALSE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_asignaciones_grupo_asignatura UNIQUE (grupo_id, asignatura_id),
    CONSTRAINT fk_asignaciones_profesor FOREIGN KEY (profesor_id) REFERENCES profesores (id) ON DELETE RESTRICT,
    CONSTRAINT fk_asignaciones_grupo FOREIGN KEY (grupo_id) REFERENCES grupos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_asignaciones_asignatura FOREIGN KEY (asignatura_id) REFERENCES asignaturas (id) ON DELETE RESTRICT,
    CONSTRAINT chk_asignaciones_ih CHECK (intensidad_horaria_semanal > 0)
);

CREATE INDEX IF NOT EXISTS idx_asignaciones_profesor ON asignaciones_academicas (profesor_id);
CREATE INDEX IF NOT EXISTS idx_asignaciones_grupo ON asignaciones_academicas (grupo_id);
CREATE INDEX IF NOT EXISTS idx_asignaciones_asignatura ON asignaciones_academicas (asignatura_id);
