-- 1. Tabla estudiantes
CREATE TABLE IF NOT EXISTS estudiantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(50) NOT NULL,
    apellidos VARCHAR(50) NOT NULL,
    documento VARCHAR(20) NOT NULL,
    fecha_nacimiento DATE,
    correo VARCHAR(100),
    telefono VARCHAR(20),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE,
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT uk_estudiantes_documento UNIQUE (documento),
    CONSTRAINT uk_estudiantes_correo UNIQUE (correo)
);

-- 2. Tabla acudientes
CREATE TABLE IF NOT EXISTS acudientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(50) NOT NULL,
    apellidos VARCHAR(50) NOT NULL,
    documento VARCHAR(20) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    telefono_alternativo VARCHAR(20),
    correo VARCHAR(100),
    direccion VARCHAR(150) NOT NULL,
    ocupacion VARCHAR(80) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_acudientes_documento UNIQUE (documento),
    CONSTRAINT uk_acudientes_correo UNIQUE (correo)
);

-- 3. Tabla estudiante_acudiente (relacion muchos a muchos con atributos propios)
CREATE TABLE IF NOT EXISTS estudiante_acudiente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL,
    acudiente_id BIGINT NOT NULL,
    parentesco VARCHAR(20) NOT NULL,
    es_principal BOOLEAN NOT NULL DEFAULT FALSE,
    convive_con_estudiante BOOLEAN NOT NULL DEFAULT FALSE,
    autorizado_retiro BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_vinculacion TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_estudiante_acudiente UNIQUE (estudiante_id, acudiente_id),
    CONSTRAINT fk_estudiante_acudiente_estudiante FOREIGN KEY (estudiante_id) REFERENCES estudiantes (id),
    CONSTRAINT fk_estudiante_acudiente_acudiente FOREIGN KEY (acudiente_id) REFERENCES acudientes (id)
);

